#!/usr/bin/env python3
"""Generate, optimize, or verify Triton kernels from the fixed problem specs.

Problems live under PROBLEMS_HOME (default /workspace/user/problems). Each
problem directory holds problem.txt, test_fixed.py, bench.py, and spec.py;
the shared _harness.py imports them. Because KernelAgent's verification
workers run a test script in a directory holding only kernel.py, the fixed
test is handed over as one self-contained script with spec.py and
_harness.py embedded.

Usage:
  generate-kernel.py generate <problem|all>
  generate-kernel.py optimize <problem|all> [--case N]
  generate-kernel.py verify <problem> [--impl kernel|optimized]
                             [--kernel PATH --label NAME]
  generate-kernel.py list

Generation and optimization need a configured LLM (OPENAI_MODEL plus the
matching API key; LLM_BACKEND selects the backend); verification does not.
Artifacts and summaries land under RESULTS_MOUNT/<problem>/, and publishing
or verifying serialize on a per-problem .results.lock. See AGENTS.md and
workspace/KernelAgent/README.md for the artifact, GPU-selection, and
acceptance contracts.
"""

