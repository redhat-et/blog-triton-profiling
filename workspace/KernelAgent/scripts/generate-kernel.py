def cmd_generate(name: str, workers: int, rounds: int, timeout_s: int) -> int:
    pdir = _problem_dir(name)
    out_dir = _results_dir(name)
    description = _problem_description(name)
    test_code = _agent_test_code(pdir)

    from triton_kernel_agent import TritonKernelAgent

    ka_common.print_banner(
        f"KernelAgent — Triton kernel generation: {name}",
        [
            ("Problem", pdir),
            ("Results dir", out_dir),
            ("Model", os.environ.get("OPENAI_MODEL", "(env default)")),
            ("Backend", os.environ.get("LLM_BACKEND", "openai")),
            (
                "Workers",
                f"{workers}  Rounds: {rounds}  "
                f"Test timeout: {timeout_s}s",
            ),
            ("GPU", _gpu_name()),
        ],
    )

    if not _require_no_cuda("generation"):
        return 1

    agent = TritonKernelAgent(
        num_workers=workers,
        max_rounds=rounds,
        log_dir=str(out_dir),
        model_name=os.environ.get("OPENAI_MODEL"),
        test_timeout_s=timeout_s,
    )
    t0 = time.time()
    result = agent.generate_kernel(
        problem_description=description,
        test_code=test_code,
        generate_default_test=False,
    )
    elapsed = time.time() - t0
    agent.cleanup()

    # A success flag without kernel_code is an agent contract violation:
    # record it as a failure rather than crashing on the missing key.
    success = bool(result.get("success")) and bool(result.get("kernel_code"))
    summary = {
        "problem": name,
        "model": os.environ.get("OPENAI_MODEL"),
        "llm_backend": os.environ.get("LLM_BACKEND"),
        "gpu": _gpu_name(),
        "workers": workers,
        "rounds": rounds,
        "elapsed_s": round(elapsed, 1),
        "success": success,
        "session_dir": result.get("session_dir"),
        "generated_at": datetime.now().isoformat(),
    }
    summary_path = out_dir / IMPL_ARTIFACTS["kernel"]["summary"]
    if success:
        kernel_path = out_dir / IMPL_ARTIFACTS["kernel"]["kernel"]
        summary.update(
            {
                "worker_id": result.get("worker_id"),
                "rounds_used": result.get("rounds"),
                "kernel_path": str(kernel_path),
            }
        )
        _publish_kernel(
            name,
            result["kernel_code"],
            summary=summary,
            description=description,
        )
        print(f"KERNEL_GENERATED: {kernel_path}")
    else:
        reason = result.get("message") or (
            "agent reported success but returned no kernel code"
            if result.get("success")
            else "unknown error"
        )
        print(f"GENERATION FAILED: {reason}")
        print(f"Inspect sessions under: {out_dir}")
        # Share the lock with the kernel this run did not replace, so
        # concurrent summary writes cannot interleave.
        with _results_lock(out_dir):
            _atomic_write_json(summary_path, summary)
    print(f"Summary: {summary_path}")
    return 0 if success else 1


