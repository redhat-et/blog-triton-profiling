def _load_cases(name: str) -> list[tuple]:
    """Benchmark cases of a problem, loaded from its spec.py."""
    return list(ka_common._load_spec(PROBLEMS_HOME, name).BENCH_CASES)


def _case_ms(bench_data: dict | None, case_index: int) -> float | None:
    """The kernel's latency in milliseconds for one benchmark case."""
    entry = find_bench_case(bench_data, case_index)
    return (entry or {}).get("kernel_ms")


def _spec_module_source(spec) -> tuple[str, str]:
    """Split a problem spec's source into (future imports, module body).

    The generated problem module already starts with a docstring, so
    spec.py's ``from __future__`` statements cannot stay where they are;
    return them separately so the caller can place them first. The rest of
    spec.py is embedded verbatim, keeping every helper and constant it
    defines available to make_inputs() and reference().
    """
    source = inspect.getsource(spec)
    tree = ast.parse(source)
    lines = source.splitlines()
    drop: set[int] = set()
    future: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ImportFrom) and node.module == "__future__":
            future.append(ast.get_source_segment(source, node) or "")
            drop.update(range(node.lineno - 1, node.end_lineno or node.lineno))
    body = "\n".join(
        line for index, line in enumerate(lines) if index not in drop
    ).strip("\n")
    return "\n".join(future), body


def _render_problem_module(name: str, case_index: int, case: tuple) -> str:
    """Render the self-contained problem module for one optimization target.

    KernelAgent's optimizer drives a Model / get_inputs() interface, so the
    text spec is adapted into a module pinned to the selected case. The
    whole spec.py is embedded (not just make_inputs()/reference()), so any
    helper or constant those functions use is present too. The docstring
    carries the full problem.txt so rewrites keep honoring every written
    requirement.
    """
    # _problem_description resolves @GPU_TARGET@ first, so the guard below
    # also catches a KA_GPU_TARGET value that cannot be embedded.
    description = _problem_description(name)
    if '"""' in description or "'''" in description:
        raise SystemExit(
            f"ERROR: {_problem_dir(name) / 'problem.txt'} (or its resolved "
            "GPU target) contains triple quotes; cannot embed it in the "
            "generated problem module"
        )
    spec = ka_common._load_spec(PROBLEMS_HOME, name)
    seed = spec.BENCH_SEED_BASE + case_index
    future_src, spec_src = _spec_module_source(spec)
    header = (
        "Problem module generated by generate-kernel.py optimize — do not "
        "edit.\n"
        f"Optimization target: benchmark case {case_index} = {case!r}.\n"
        "Model is the stateless PyTorch reference used as the baseline; the "
        "optimized\n"
        "kernel must keep computing the result itself, in Triton, with the "
        "exact wrapper\n"
        "signature required by the problem description below. get_inputs() "
        "returns the\n"
        "kernel_function arguments in calling order, so the benchmark and "
        "profiling\n"
        "harnesses invoke the kernel exactly like the fixed benchmark does. "
        "The\n"
        "problem's spec.py is copied verbatim below, so every helper and "
        "constant it\n"
        "defines is available to make_inputs() and reference().\n\n"
    )
    future_block = f"{future_src}\n\n" if future_src else ""
    body = f'''{future_block}import torch
import torch.nn as nn


{spec_src}


class Model(nn.Module):
    """PyTorch baseline (reference only); see reference() above."""

    def forward(self, *args):
        return reference(*args)


CASE = {case!r}
SEED = {seed}


def get_inputs():
    return list(make_inputs(CASE, SEED))


def get_init_inputs():
    return []
'''
    return f'"""{header}{description}"""\n\n{body}'


def _optimization_verdict(
    source_code: str,
    candidate_code: str,
    source_bench: dict,
    candidate_bench: dict,
    case_index: int,
) -> tuple[bool, str | None, dict]:
    """Decide whether an optimized candidate replaces the saved artifact.

    The candidate must differ from the source and be strictly faster on the
    selected case when both are measured by the fixed benchmark (the
    optimizer's internal timings only approximate the case).
    """
    source_ms = _case_ms(source_bench, case_index)
    candidate_ms = _case_ms(candidate_bench, case_index)
    timing = {"source_case_ms": source_ms, "candidate_case_ms": candidate_ms}
    if candidate_code == source_code:
        return False, "best kernel is the unchanged source kernel", timing
    if source_ms is None or candidate_ms is None:
        return False, f"benchmark result missing case {case_index}", timing
    if not candidate_ms < source_ms:
        return (
            False,
            f"candidate not faster on case {case_index}: "
            f"{candidate_ms:.4f}ms vs {source_ms:.4f}ms",
            timing,
        )
    return True, None, timing


def cmd_optimize(
    name: str, case_index: int, workers: int, rounds: int, timeout_s: int
) -> int:
    pdir = _problem_dir(name)
    out_dir = _results_dir(name)
    source = out_dir / IMPL_ARTIFACTS["kernel"]["kernel"]
    if not source.is_file():
        print(
            f"ERROR: {source} not found; run 'generate-kernel.py generate "
            f"{name}' first"
        )
        return 1
    cases = _load_cases(name)
    if not 0 <= case_index < len(cases):
        raise SystemExit(
            f"ERROR: case must be in 0..{len(cases) - 1} for {name} "
            f"(got {case_index})"
        )
    case = cases[case_index]

    # Resolve the selection before any session work, so an invalid selection
    # leaves no session directory behind. No CUDA call runs here: the
    # manager forks workers.
    try:
        selected_gpu_ids, resolved_gpu_name = _resolve_gpu_selection()
    except GpuSelectionError as exc:
        print(f"ERROR: {exc}")
        return 1
    # One target GPU per session: the optimizer shares timings, profiles,
    # and specs across workers, so mixed GPU models would corrupt the
    # search. The whole selection is still recorded in the summary.
    gpu_ids = selected_gpu_ids[:1]
    gpu_name = os.environ.get("KA_GPU_NAME") or resolved_gpu_name
    if gpu_name is None:
        print(
            "ERROR: could not detect the GPU name for the optimizer (the "
            "CUDA probe and nvidia-smi were unavailable or could not name "
            "the selected device); set KA_GPU_NAME and retry"
        )
        return 1

    test_code = _agent_test_code(pdir)

    # Snapshot the source under the lock and use only the snapshot: the
    # optimization, hash, benchmarks, and verdict then describe one
    # immutable kernel even if generation republishes it mid-run.
    with _results_lock(out_dir):
        if not source.is_file():
            print(
                f"ERROR: {source} not found; run 'generate-kernel.py "
                f"generate {name}' first"
            )
            return 1
        source_bytes = source.read_bytes()

    # Render and compile-check the module before creating a session
    # directory, so a malformed spec fails fast without leaving one behind.
    problem_source = _render_problem_module(name, case_index, case)
    try:
        compile(problem_source, f"{name}/problem.py", "exec")
    except SyntaxError as exc:
        print(
            f"ERROR: generated problem module for {name} does not compile: "
            f"{exc}"
        )
        return 1

    # mkdtemp allocates atomically, so concurrent optimizers cannot share a
    # session directory.
    session_dir = Path(
        tempfile.mkdtemp(
            dir=out_dir,
            prefix=f"optimize_session_{datetime.now():%Y%m%d_%H%M%S}_",
        )
    )
    snapshot = session_dir / "source_kernel.py"
    snapshot.write_bytes(source_bytes)
    source_text = source_bytes.decode("utf-8")
    source_sha256 = sha256_bytes(source_bytes)
    problem_file = session_dir / "problem.py"
    problem_file.write_text(problem_source, encoding="utf-8")

    ka_common.print_banner(
        f"KernelAgent — Triton kernel optimization: {name}",
        [
            ("Source kernel", source),
            ("Case", f"{case_index}  {case}"),
            ("Session dir", session_dir),
            ("Model", os.environ.get("OPENAI_MODEL", "(env default)")),
            ("Backend", os.environ.get("LLM_BACKEND", "openai")),
            (
                "Workers",
                f"{workers}  Rounds: {rounds}  "
                f"Test timeout: {timeout_s}s",
            ),
            ("Selected GPUs", selected_gpu_ids),
            ("Optimizer GPU", f"{gpu_ids}  (specs name: {gpu_name})"),
        ],
    )

    from triton_kernel_agent.opt_manager import OptimizationManager

    # One worker runs greedy; more workers fan each round out across that
    # many ranked bottlenecks (beam width 1).
    if workers <= 1:
        strategy = "greedy"
        strategy_config = None
    else:
        strategy = "beam_search"
        strategy_config = {"num_top_kernels": 1, "num_bottlenecks": workers}

    if not _require_no_cuda("optimizer"):
        return 1

    manager = OptimizationManager(
        strategy=strategy,
        num_workers=workers,
        max_rounds=rounds,
        log_dir=session_dir,
        database_path=session_dir / "program_db.json",
        strategy_config=strategy_config,
        openai_model=os.environ.get("OPENAI_MODEL"),
        gpu_name=gpu_name,
        gpu_ids=gpu_ids,
        test_timeout_s=timeout_s,
    )
    t0 = time.time()
    result = manager.run_optimization(
        initial_kernel=source_text,
        problem_file=problem_file,
        test_code=test_code,
    )
    elapsed = time.time() - t0

    summary = {
        "problem": name,
        "case": case_index,
        "case_spec": str(case),
        "model": os.environ.get("OPENAI_MODEL"),
        "llm_backend": os.environ.get("LLM_BACKEND"),
        "gpu": resolved_gpu_name or _gpu_name(),
        "selected_gpu_ids": selected_gpu_ids,
        "optimizer_gpu_ids": gpu_ids,
        "workers": workers,
        "strategy": strategy,
        "rounds": rounds,
        "source_kernel_path": str(source),
        "source_kernel_snapshot": str(snapshot),
        "source_kernel_sha256": source_sha256,
        "session_dir": str(session_dir),
        "elapsed_s": round(elapsed, 1),
        "manager_result": {
            key: result.get(key)
            for key in (
                "best_time_ms",
                "total_rounds",
                "initial_kernel_time_ms",
                "pytorch_baseline_ms",
                "pytorch_compile_ms",
            )
        },
        "generated_at": datetime.now().isoformat(),
    }
    # Each session keeps its own summary; the shared one describes the
    # latest completed attempt.
    summary_name = IMPL_ARTIFACTS["optimized"]["summary"]
    session_summary_path = session_dir / summary_name
    shared_summary_path = out_dir / summary_name

    def finish_failure(**extra) -> int:
        summary.update(extra)
        summary["success"] = False
        _atomic_write_json(session_summary_path, summary)
        with _results_lock(out_dir):
            _atomic_write_json(shared_summary_path, summary)
        print(
            f"Summary: {session_summary_path} "
            f"(shared: {shared_summary_path})"
        )
        return 1

    if not result.get("success") or not result.get("kernel_code"):
        reason = result.get("error") or "optimization produced no kernel"
        print(f"OPTIMIZATION FAILED: {reason}")
        print(f"Inspect the session under: {session_dir}")
        return finish_failure(reason=reason)

    candidate = result["kernel_code"]
    candidate_path = session_dir / "candidate_kernel.py"
    candidate_path.write_text(candidate, encoding="utf-8")

    # Case-filtered: the verdict reads only this case, and the published
    # record carries only this case's benchmark entry.
    print("==> validating the candidate with the fixed test and benchmark")
    candidate_bench, stage, reason = _check_kernel(
        name, candidate_path, timeout_s, case_filter=case_index
    )
    if candidate_bench is None:
        print(f"OPTIMIZATION FAILED: candidate failed {stage}: {reason}")
        print(f"Inspect the session under: {session_dir}")
        return finish_failure(stage=stage, reason=reason)

    print("==> benchmarking the source kernel for comparison")
    source_bench, stage, reason = _check_kernel(
        name, snapshot, timeout_s, case_filter=case_index, run_test=False
    )
    if source_bench is None:
        print(f"ERROR: source kernel failed {stage}: {reason}; cannot compare")
        return finish_failure(stage=f"source_{stage}", reason=reason)

    accept, reason, timing = _optimization_verdict(
        source_text,
        candidate,
        source_bench,
        candidate_bench,
        case_index,
    )
    summary.update(timing)
    if not accept:
        print(f"OPTIMIZATION FAILED: {reason}")
        print(f"Inspect the session under: {session_dir}")
        return finish_failure(reason=reason)

    kernel_path = out_dir / IMPL_ARTIFACTS["optimized"]["kernel"]
    record = {
        "problem": name,
        "impl": "optimized",
        "kernel_path": str(kernel_path),
        "kernel_sha256": sha256_bytes(candidate.encode("utf-8")),
        "gpu": _gpu_name(),
        "verified_at": datetime.now().isoformat(),
        "success": True,
        "test_passed": True,
        "benchmark": candidate_bench,
    }
    speedup = (
        round(timing["source_case_ms"] / timing["candidate_case_ms"], 3)
        if timing["candidate_case_ms"]
        else None
    )
    summary.update(
        {
            "success": True,
            "reason": None,
            "optimized_kernel_path": str(kernel_path),
            "optimized_kernel_sha256": record["kernel_sha256"],
            "speedup": speedup,
        }
    )
    # One critical section publishes the kernel, its record, and the
    # shared summary, so the summary always describes the kernel on disk.
    kernel_path = _publish_kernel(
        name, candidate, record, summary, impl="optimized"
    )
    _atomic_write_json(session_summary_path, summary)
    print(
        f"Summary: {session_summary_path} (shared: {shared_summary_path})"
    )
    print(
        f"KERNEL_OPTIMIZED: {kernel_path} (case {case_index}: "
        f"{timing['source_case_ms']:.4f}ms -> "
        f"{timing['candidate_case_ms']:.4f}ms, {speedup}x)"
    )
    return 0


# --- CLI -------------------------------------------------------------------


def main() -> int:
    problems = available_problems(PROBLEMS_HOME)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "command", choices=["generate", "optimize", "verify", "list"]
    )
    parser.add_argument(
        "problem",
        nargs="?",
        default="all",
        help="problem name or 'all' (default: all; one of "
        f"{', '.join(problems)})",
    )
    parser.add_argument(
        "--case",
        type=int,
        default=0,
        help="benchmark case index to optimize (default: 0)",
    )
    parser.add_argument(
        "--impl",
        choices=["kernel", "optimized"],
        default="kernel",
        help="which saved kernel to verify (default: kernel)",
    )
    parser.add_argument(
        "--kernel",
        type=Path,
        default=None,
        help="verify this external kernel file instead of a saved artifact "
        "(verify command only; requires --label and a single problem)",
    )
    parser.add_argument(
        "--label",
        default=None,
        help="record name for --kernel verification: "
        "results/<problem>/verify_<label>.json (requires --kernel)",
    )
    parser.add_argument(
        "--workers",
        type=int,
        default=_env_int("KA_WORKERS", 1),
        help="parallel kernel candidates to generate or optimize "
        "(default: KA_WORKERS or 1)",
    )
    parser.add_argument(
        "--rounds",
        type=int,
        default=_env_int("KA_ROUNDS", 5),
        help="max refinement or optimization rounds (default: KA_ROUNDS or 5)",
    )
    parser.add_argument(
        "--test-timeout-s",
        type=int,
        default=180,
        help="per-test subprocess timeout in seconds (default: 180)",
    )
    args = parser.parse_args()

    if args.command in ("generate", "optimize"):
        if args.workers < 1:
            raise SystemExit(
                f"ERROR: --workers must be >= 1 (got {args.workers}); it "
                "sets the number of parallel kernel candidates"
            )
        if args.rounds < 1:
            raise SystemExit(
                f"ERROR: --rounds must be >= 1 (got {args.rounds}); it sets "
                "the number of refinement or optimization rounds"
            )

    if args.kernel is not None or args.label is not None:
        if args.command != "verify":
            raise SystemExit(
                "ERROR: --kernel/--label apply to the verify command only"
            )
        if args.kernel is None or args.label is None:
            raise SystemExit(
                "ERROR: --kernel and --label must be passed together"
            )
        if args.impl != "kernel":
            raise SystemExit(
                "ERROR: --kernel names the kernel source explicitly; "
                "it cannot be combined with --impl"
            )
        if args.problem == "all":
            raise SystemExit(
                "ERROR: --kernel verifies one problem's contract; "
                "pass a single problem, not 'all'"
            )

    if args.command == "list":
        for name in problems:
            print(name)
        return 0

    if args.problem == "all":
        names = list(problems)
    elif args.problem in problems:
        names = [args.problem]
    else:
        raise SystemExit(
            f"ERROR: unknown problem '{args.problem}' (choose from "
            f"{', '.join(problems)} or 'all')"
        )

    rc = 0
    for name in names:
        if args.command == "generate":
            rc |= cmd_generate(
                name, args.workers, args.rounds, args.test_timeout_s
            )
        elif args.command == "optimize":
            rc |= cmd_optimize(
                name, args.case, args.workers, args.rounds, args.test_timeout_s
            )
        else:
            rc |= cmd_verify(
                name, args.test_timeout_s, args.impl, args.kernel, args.label
            )
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
