# --- Problem and results helpers -------------------------------------------


def _problem_dir(name: str) -> Path:
    pdir = PROBLEMS_HOME / name
    for required in PROBLEM_FILES:
        if not (pdir / required).is_file():
            raise SystemExit(f"ERROR: {pdir} is missing {required}")
    return pdir


def _harness_path() -> Path:
    path = PROBLEMS_HOME / SHARED_HARNESS
    if not path.is_file():
        raise SystemExit(f"ERROR: {path} not found")
    return path


def _copy_problem_files(pdir: Path, dest_dir: Path) -> None:
    """Stage a problem's test files and the shared harness beside a kernel."""
    for fname in PROBLEM_FILES[1:]:  # problem.txt is handled separately
        shutil.copy2(pdir / fname, dest_dir / fname)
    shutil.copy2(_harness_path(), dest_dir / SHARED_HARNESS)


def _results_dir(name: str) -> Path:
    rdir = RESULTS_MOUNT / name
    rdir.mkdir(parents=True, exist_ok=True)
    return rdir


@contextlib.contextmanager
def _results_lock(rdir: Path):
    """Serialize artifact, record, and summary publication per problem.

    flock() is per open file description, so this blocks across processes
    sharing the results mount and across threads opening the lock separately.
    """
    rdir.mkdir(parents=True, exist_ok=True)
    with _exclusive_lock(rdir / ".results.lock"):
        yield


# --- Self-contained test payload for KernelAgent ---------------------------

_AGENT_TEST_TEMPLATE = '''\
"""Self-contained fixed test, generated by generate-kernel.py.

Runs in an isolated verification directory that holds only kernel.py and
this file. The bootstrap below installs the two modules the problem's
test_fixed.py imports — spec (this problem's case data and reference
ops) and _harness (the shared contract-check scaffolding) — from the
sources embedded here, then executes the fixed test's own source under
__main__. Both modules are entered into sys.modules before the test
runs, so its imports resolve to the embedded sources rather than to
anything found on this directory's path.
"""
import sys
import types


def _ka_embed(name, source):
    """Install `source` as module `name`, as an import of <name>.py."""
    module = types.ModuleType(name)
    module.__file__ = name + ".py"
    sys.modules[name] = module
    exec(compile(source, module.__file__, "exec"), module.__dict__)


{embeds}
_ka_test_globals = {{"__name__": "__main__", "__file__": "test_fixed.py"}}
exec(compile({test}, "test_fixed.py", "exec"), _ka_test_globals)
'''


def _agent_test_code(pdir: Path) -> str:
    """The fixed test as one self-contained script for KernelAgent.

    spec.py and _harness.py are embedded through repr() ahead of
    test_fixed.py's source. Only text is read here — importing them would
    initialize torch/CUDA in this process, which forks the workers.
    """
    sources = [
        ("spec", (pdir / "spec.py").read_text(encoding="utf-8")),
        # Embedded second: the harness may import the spec, never the
        # reverse, so _ka_embed("_harness", ...) can find it.
        ("_harness", _harness_path().read_text(encoding="utf-8")),
    ]
    embeds = "".join(
        f"_ka_embed({name!r}, {source!r})\n" for name, source in sources
    )
    test_src = (pdir / "test_fixed.py").read_text(encoding="utf-8")
    return _AGENT_TEST_TEMPLATE.format(embeds=embeds, test=repr(test_src))


# --- GPU selection and hardware description --------------------------------


class GpuSelectionError(Exception):
    """CUDA_VISIBLE_DEVICES cannot be resolved for the optimizer."""


def _smi_gpus() -> list[dict] | None:
    """GPU inventory (index, UUID, name) from nvidia-smi, or None.

    nvidia-smi ignores CUDA_VISIBLE_DEVICES and is safe to run in the
    parent process. Its index ordering is not CUDA's, so its indices never
    map a numeric selector to hardware.
    """
    rows = ka_common._smi_inventory(
        ("index", "uuid", "name"), timeout=15
    )
    if rows is None:
        return None
    gpus = [
        {"index": int(index), "uuid": uuid, "name": name}
        for index, uuid, name in rows
        if index.isdigit() and uuid and name
    ]
    return gpus or None


def _run_cuda_probe(env: dict) -> list[dict] | None:
    """Validated CUDA inventory from one probe child, or None.

    None when the probe cannot run or any entry is malformed; an empty list
    means CUDA itself reported no devices.
    """
    devices, _ = ka_common._run_cuda_probe(env=env)
    if devices is None:
        return None
    inventory: list[dict] = []
    for entry in devices:
        validated = ka_common._probe_device_entry(entry)
        if validated is None or validated["ordinal"] != len(inventory):
            return None
        inventory.append(validated)
    return inventory


def _cuda_inventory() -> list[dict] | None:
    """CUDA inventory in CUDA's own device order.

    A numeric CUDA_VISIBLE_DEVICES entry is a CUDA ordinal, so mapping it to
    hardware needs the unfiltered ordering: strip the variable in the probe
    child. When it is unset, the visible ordering is already unfiltered.
    """
    if "CUDA_VISIBLE_DEVICES" not in os.environ:
        devices = _visible_cuda_devices()
        return None if devices is None else list(devices)
    env = dict(os.environ)
    env.pop("CUDA_VISIBLE_DEVICES", None)
    return _run_cuda_probe(env)


@functools.lru_cache(maxsize=1)
def _visible_cuda_devices() -> tuple[dict, ...] | None:
    """Probed inventory under the current environment; device 0 is the one
    tests and benchmarks use. Cached so every metadata caller shares one
    probe child."""
    devices = _run_cuda_probe(dict(os.environ))
    return None if devices is None else tuple(devices)


def _gpu_name() -> str:
    """Name of the CUDA device tests and benchmarks use, or "unknown"."""
    devices = _visible_cuda_devices()
    return devices[0]["name"] if devices else "unknown"


def _cuda_is_initialized() -> bool:
    """Whether CUDA is live in this process. Never initializes it."""
    torch = sys.modules.get("torch")
    if torch is None:
        return False
    try:
        return bool(torch.cuda.is_initialized())
    except Exception:
        return False


def _require_no_cuda(role: str) -> bool:
    """Guard the no-CUDA-before-fork invariant.

    Prints and returns False when CUDA is already live, so a future edit
    that initializes CUDA ahead of a fork fails loudly here instead of
    handing the forked workers broken state.
    """
    if not _cuda_is_initialized():
        return True
    print(
        "ERROR: CUDA is already initialized in this process; the "
        f"{role} workers forked below would inherit broken CUDA state"
    )
    return False


_GPU_TARGET_TOKEN = "@GPU_TARGET@"


def _gpu_architecture(name: str) -> str | None:
    """Architecture for a catalogued GPU, or None (best effort).

    The optimizer's specs modules are pure Python (no torch/CUDA), so this
    import is safe in the parent process that later forks the workers.
    """
    try:
        from kernel_perf_agent.kernel_opt.diagnose_prompt.gpu_specs import (
            get_gpu_specs,
        )
    except ImportError:
        return None
    try:
        specs = get_gpu_specs(name)
    except Exception:
        # Enriching the description must never fail generation.
        return None
    architecture = (specs or {}).get("architecture")
    if isinstance(architecture, str) and architecture.strip():
        return architecture.strip()
    return None


def _gpu_target() -> str | None:
    """Hardware description for @GPU_TARGET@; KA_GPU_TARGET overrides.

    The detected text carries the device name, memory, compute capability,
    the catalogued architecture, and sm_<major><minor>, for example
    "NVIDIA GeForce RTX 5090 (32GB, compute capability 12.0, Blackwell,
    sm_120)". An uncatalogued GPU omits only the architecture.
    """
    override = (os.environ.get("KA_GPU_TARGET") or "").strip()
    if override:
        return override
    devices = _visible_cuda_devices()
    if not devices:
        return None
    device = devices[0]
    details = []
    memory = device.get("total_memory")
    if isinstance(memory, int) and memory > 0:
        details.append(f"{round(memory / (1024 ** 3))}GB")
    major, minor = device.get("major"), device.get("minor")
    has_cc = isinstance(major, int) and isinstance(minor, int)
    if has_cc:
        details.append(f"compute capability {major}.{minor}")
    architecture = _gpu_architecture(device["name"])
    if architecture:
        details.append(architecture)
    if has_cc:
        details.append(f"sm_{major}{minor}")
    if not details:
        return device["name"]
    return f"{device['name']} ({', '.join(details)})"


def _problem_description(name: str) -> str:
    """problem.txt for one problem, with @GPU_TARGET@ resolved."""
    path = _problem_dir(name) / "problem.txt"
    text = path.read_text(encoding="utf-8")
    if _GPU_TARGET_TOKEN not in text:
        return text
    target = _gpu_target()
    if target is None:
        raise SystemExit(
            f"ERROR: {path} targets {_GPU_TARGET_TOKEN} but no GPU "
            "description could be resolved (the CUDA probe was "
            "unavailable or reported no devices); set KA_GPU_TARGET and "
            "retry"
        )
    return text.replace(_GPU_TARGET_TOKEN, target)


def _selected_gpu_name(
    selector: int | str,
    cuda_devices: list[dict] | None,
    smi_gpus: list[dict] | None,
) -> str | None:
    """Specs name of the first selected device, or None.

    A UUID selector names the hardware directly. A numeric selector is a
    CUDA ordinal and needs the probe inventory: without one, no name is
    guessed from nvidia-smi's ordering, which may differ from CUDA's.
    """
    if isinstance(selector, str):
        return next(
            (
                gpu["name"]
                for gpu in smi_gpus or []
                if gpu["uuid"] == selector
            ),
            None,
        )
    if cuda_devices is None:
        return None
    device = cuda_devices[selector]
    if device["uuid"] is not None:
        for gpu in smi_gpus or []:
            if gpu["uuid"].lower() == device["uuid"].lower():
                return gpu["name"]
    return device["name"]


def _deduplicate_gpus(
    selectors: list[int | str], cuda_devices: list[dict] | None
) -> list[int | str]:
    """Drop selectors that name an already-selected physical GPU.

    Identity is the CUDA inventory's UUID for a numeric selector and the
    selector itself for a UUID. When the probe cannot establish a numeric
    selector's identity, only equal selectors collapse.
    """
    seen: set[tuple[str, str | int]] = set()
    deduplicated: list[int | str] = []
    for selector in selectors:
        if isinstance(selector, str):
            key = ("uuid", selector.lower())
        elif cuda_devices is not None and cuda_devices[selector]["uuid"]:
            key = ("uuid", cuda_devices[selector]["uuid"].lower())
        else:
            key = ("selector", selector)
        if key not in seen:
            seen.add(key)
            deduplicated.append(selector)
    return deduplicated


def _resolve_gpu_selection() -> tuple[list[int | str], str | None]:
    """Resolve CUDA_VISIBLE_DEVICES to selectors and the first device's name.

    Numeric entries remain CUDA ordinals and are validated through the
    isolated probe; UUID entries resolve against nvidia-smi. The whole
    selection is validated and deduplicated, though the caller runs on its
    first entry. Raises GpuSelectionError when the selection cannot be
    honored.
    """
    raw = os.environ.get("CUDA_VISIBLE_DEVICES")
    if raw is None:
        # Unset: every GPU is visible, in CUDA order.
        cuda = _cuda_inventory()
        if cuda:
            return (
                list(range(len(cuda))),
                _selected_gpu_name(0, cuda, _smi_gpus()),
            )
        if cuda is not None:
            raise GpuSelectionError(
                "CUDA_VISIBLE_DEVICES is unset, but the CUDA runtime "
                "reports no device; the optimizer needs at least one GPU"
            )
        # Probe unavailable: fall back to CUDA's default device, unnamed.
        return [0], None

    entries = [entry.strip() for entry in raw.split(",") if entry.strip()]
    if not entries or entries == ["-1"]:
        raise GpuSelectionError(
            f"CUDA_VISIBLE_DEVICES='{raw}' hides every CUDA device; the "
            "optimizer needs at least one GPU"
        )

    # Validate the selection and resolve UUID entries before the (slow)
    # probe runs, so malformed selections fail fast.
    gpus = _smi_gpus()
    selectors: list[int | str] = []
    for entry in entries:
        if entry.startswith("MIG-") or (
            entry.startswith("GPU-") and "/" in entry
        ):
            raise GpuSelectionError(
                f"CUDA_VISIBLE_DEVICES='{entry}' selects a MIG instance, "
                "but the optimizer's workers pin whole GPUs; select a "
                "whole GPU"
            )
        if entry.isdigit():
            index = int(entry)
            if index not in selectors:
                selectors.append(index)
        elif entry.startswith("GPU-"):
            if gpus is None:
                raise GpuSelectionError(
                    f"cannot resolve CUDA_VISIBLE_DEVICES='{entry}' "
                    "without nvidia-smi; select GPUs by numeric index"
                )
            matches = [gpu for gpu in gpus if gpu["uuid"].startswith(entry)]
            if not matches:
                raise GpuSelectionError(
                    f"CUDA_VISIBLE_DEVICES='{entry}' matches no GPU UUID "
                    "reported by nvidia-smi"
                )
            if len(matches) > 1:
                raise GpuSelectionError(
                    f"CUDA_VISIBLE_DEVICES='{entry}' is an ambiguous GPU "
                    "UUID prefix; use the full UUID"
                )
            uuid = matches[0]["uuid"]
            if uuid not in selectors:
                selectors.append(uuid)
        else:
            raise GpuSelectionError(
                f"unsupported CUDA_VISIBLE_DEVICES entry '{entry}' (use a "
                "numeric GPU index or a GPU-<uuid> selector)"
            )

    if not any(isinstance(selector, int) for selector in selectors):
        # UUID-only selection: nvidia-smi already identified the hardware.
        return selectors, _selected_gpu_name(selectors[0], None, gpus)

    # A numeric index is present, so resolve every index through CUDA.
    cuda = _cuda_inventory()
    if cuda is not None:
        for selector in selectors:
            if isinstance(selector, int) and selector >= len(cuda):
                raise GpuSelectionError(
                    f"CUDA_VISIBLE_DEVICES='{raw}' names CUDA device "
                    f"{selector}, but the CUDA runtime reports only "
                    f"{len(cuda)} device(s)"
                )
        deduplicated = _deduplicate_gpus(selectors, cuda)
        return deduplicated, _selected_gpu_name(
            deduplicated[0], cuda, gpus
        )

    # Probe unavailable: indices still pass through, but no name is guessed
    # from nvidia-smi's ordering. Range-check against nvidia-smi only when
    # it actually reported an inventory.
    if gpus is not None:
        smi_indices = sorted(gpu["index"] for gpu in gpus)
        for selector in selectors:
            if isinstance(selector, int) and selector not in smi_indices:
                raise GpuSelectionError(
                    f"CUDA_VISIBLE_DEVICES='{raw}' names GPU {selector}, "
                    f"but nvidia-smi reports only {smi_indices}"
                )
    deduplicated = _deduplicate_gpus(selectors, None)
    return deduplicated, _selected_gpu_name(deduplicated[0], None, gpus)


# --- Publication -----------------------------------------------------------


def _publish_kernel(
    name: str,
    kernel_code: str,
    record: dict | None = None,
    summary: dict | None = None,
    *,
    impl: str = "kernel",
    description: str | None = None,
) -> Path:
    """Publish a saved kernel and its optional metadata under one lock.

    The summary is the implementation's shared run summary, written in the
    same critical section as the kernel so it always describes the artifact
    currently on disk. description is the resolved problem text when the
    caller already built it for the agent; it is re-read only when absent.
    """
    pdir = _problem_dir(name)
    out_dir = _results_dir(name)
    artifacts = IMPL_ARTIFACTS[impl]
    kernel_path = out_dir / artifacts["kernel"]
    record_path = out_dir / artifacts["record"]
    with _results_lock(out_dir):
        # The old record describes the kernel being replaced; drop it so a
        # stale success never outlives its artifact.
        record_path.unlink(missing_ok=True)
        # The profiler reads this artifact without taking .results.lock, so
        # publish by replacement to keep it complete.
        _atomic_write_text(kernel_path, kernel_code)
        _copy_problem_files(pdir, out_dir)
        # Provenance: the spec the agent saw, with @GPU_TARGET@ resolved.
        _atomic_write_text(
            out_dir / "problem.txt",
            description if description is not None
            else _problem_description(name),
        )
        if record is not None:
            _atomic_write_json(record_path, record)
        if summary is not None:
            _atomic_write_json(out_dir / artifacts["summary"], summary)
    return kernel_path


# --- Verification ----------------------------------------------------------


def _parse_bench_json(stdout: str) -> dict | None:
    return last_marker_json(stdout, "BENCH_JSON ")


def _check_kernel(
    name: str,
    kernel: Path,
    timeout_s: int,
    case_filter: int | None = None,
    run_test: bool = True,
) -> tuple[dict | None, str | None, str | None]:
    """Run the fixed test, then the benchmark, against one kernel file.

    Both run in an isolated temporary directory. case_filter restricts the
    benchmark — never the fixed test — to one case via KA_BENCH_CASE; the
    optimizer's comparison uses it because only that case's timing feeds
    the verdict. run_test=False skips the fixed test, for the optimizer's
    source comparison whose benchmark already validates every case.
    Returns (bench_data, stage, reason).
    """
    pdir = _problem_dir(name)
    with tempfile.TemporaryDirectory(prefix=f"check_{name}_") as tmp:
        tmp_dir = Path(tmp)
        shutil.copy2(kernel, tmp_dir / "kernel.py")
        _copy_problem_files(pdir, tmp_dir)

        def run_stage(
            script: str, env: dict | None = None
        ) -> subprocess.CompletedProcess | None:
            """Run one problem script in tmp_dir; None on timeout."""
            print(f"==> running {script}")
            try:
                proc = subprocess.run(
                    [sys.executable, script],
                    cwd=tmp_dir,
                    capture_output=True,
                    text=True,
                    timeout=timeout_s,
                    env=env,
                )
            except subprocess.TimeoutExpired:
                return None
            print(proc.stdout, end="")
            return proc

        # An ambient KA_BENCH_CASE (e.g. exported by a wrapper) must not
        # silently restrict the benchmark published by verify; only an
        # explicit case_filter may set it. The fixed test ignores it, but
        # gets the same cleaned environment.
        base_env = {
            key: value
            for key, value in os.environ.items()
            if key != "KA_BENCH_CASE"
        }

        test = run_stage("test_fixed.py", env=base_env) if run_test else None
        test_passed = (
            test is not None
            and test.returncode == 0
            and "PASS" in test.stdout
        )
        if run_test and not test_passed:
            if test is not None:
                print(test.stderr, end="", file=sys.stderr)
            reason = (
                f"timeout after {timeout_s}s"
                if test is None
                else "fixed test failed"
            )
            return None, "test", reason

        bench_env = dict(base_env)
        if case_filter is not None:
            bench_env["KA_BENCH_CASE"] = str(case_filter)
        bench = run_stage("bench.py", env=bench_env)
        if bench is None:
            return None, "benchmark", f"timeout after {timeout_s}s"
        bench_data = _parse_bench_json(bench.stdout)
        if bench.returncode != 0 or bench_data is None:
            print(bench.stderr, end="", file=sys.stderr)
            reason = (
                "benchmark exited nonzero"
                if bench.returncode != 0
                else "benchmark output missing valid BENCH_JSON"
            )
            return None, "benchmark", reason
        return bench_data, None, None


def cmd_verify(
    name: str,
    timeout_s: int,
    impl: str = "kernel",
    kernel_path: Path | None = None,
    label: str | None = None,
) -> int:
    # External-kernel records are named by their label, so validate it
    # before the lock would publish a record under an unusable name.
    if kernel_path is not None:
        validate_label(label)
    # The lock spans the whole run so generation or optimization cannot
    # replace the kernel while this verification tests it.
    with _results_lock(RESULTS_MOUNT / name):
        out_dir = RESULTS_MOUNT / name
        if kernel_path is not None:
            # Verify an external file, recording under verify_<label>.json
            # and leaving the impl-based records untouched.
            kernel = Path(kernel_path)
            verify_path = out_dir / f"verify_{label}.json"
        else:
            kernel = out_dir / IMPL_ARTIFACTS[impl]["kernel"]
            verify_path = out_dir / IMPL_ARTIFACTS[impl]["record"]
        # Drop any previous record up front: a failed re-verification must
        # not leave a stale success behind. This precedes problem
        # validation, which exits on missing files.
        verify_path.unlink(missing_ok=True)
        _problem_dir(name)
        if not kernel.is_file():
            if kernel_path is not None:
                how = "pass an existing kernel file"
            elif impl == "kernel":
                how = f"run 'generate-kernel.py generate {name}' first"
            else:
                how = f"run 'generate-kernel.py optimize {name}' first"
            print(f"ERROR: {kernel} not found; {how}")
            return 1

        impl_desc = impl if kernel_path is None else f"external, label {label}"
        ka_common.print_banner(
            f"KernelAgent — kernel verification: {name} ({impl_desc})"
        )
        print(f"Kernel: {kernel}")

        record = {
            "problem": name,
            "impl": impl if kernel_path is None else "external",
            "kernel_path": str(kernel),
            "kernel_sha256": sha256_file(kernel),
            "gpu": None,
            "verified_at": datetime.now().isoformat(),
        }
        if kernel_path is not None:
            record["label"] = label

        def fail(stage: str, reason: str) -> int:
            record.update(
                {"success": False, "stage": stage, "reason": reason}
            )
            _atomic_write_json(verify_path, record)
            print(f"VERIFY_FAILED: {name} ({stage}: {reason})")
            print(f"Record: {verify_path}")
            return 1

        bench_data, stage, reason = _check_kernel(name, kernel, timeout_s)
        if bench_data is None:
            # No benchmark ran, so its BENCH_JSON cannot supply the name.
            record["gpu"] = _gpu_name()
            record["test_passed"] = stage != "test"
            return fail(stage, reason)

        record.update(
            {
                "success": True,
                "test_passed": True,
                "gpu": bench_data.get("gpu", "unknown"),
                "benchmark": bench_data,
            }
        )
        _atomic_write_json(verify_path, record)
        print(
            f"VERIFY_OK: {name} (fixed test PASS, benchmark saved to "
            f"{verify_path})"
        )
        return 0


