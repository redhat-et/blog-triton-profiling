# Stage: optimize the baseline once per round budget


def _accept_optimized_kernel(
    exp_dir: Path,
    problem_dir: Path,
    problem_key: str,
    record: dict,
    summary: dict,
    case: int,
) -> bool:
    """Attribute an accepted optimization result: optimized_kernel.py, the
    summary's recorded hash, and the verification record generate-kernel.py
    published beside it must all describe the same bytes. Fills the
    record's kernel/verify/bench fields and returns False when any check
    fails (the record then says why)."""
    optimized = problem_dir / IMPL_ARTIFACTS["optimized"]["kernel"]
    if not optimized.is_file():
        return _fail_record(
            record,
            "failed",
            "optimization",
            "summary reports success but optimized_kernel.py is missing",
            f"{problem_key} accepted kernel missing",
        )
    record.update(
        {
            "status": "accepted",
            "kernel_path": _rel(exp_dir, optimized),
            "kernel_sha256": sha256_file(optimized),
        }
    )
    recorded_sha = summary.get("optimized_kernel_sha256")
    if recorded_sha and recorded_sha != record["kernel_sha256"]:
        return _fail_record(
            record,
            "hash_mismatch",
            "optimization",
            "optimization summary describes a different kernel",
            f"{problem_key} summary hash mismatch",
        )

    # cmd_optimize already validated the accepted kernel — the fixed test
    # plus the benchmark — and published verify_optimized.json beside it
    # in the same critical section that published the kernel itself (see
    # _publish_kernel in generate-kernel.py), so re-running the verify
    # subprocess here would repeat that GPU work on the same bytes. One
    # read of the published record serves both the bench entry and the
    # attribution check.
    verify = problem_dir / IMPL_ARTIFACTS["optimized"]["record"]
    verify_record = load_json_object(verify)
    if (
        verify_record is None
        or not verify_record.get("success")
        or not verify_record.get("test_passed")
    ):
        record["verify_status"] = "failed"
        return _fail_record(
            record,
            "accepted",
            "verify",
            "optimization published no successful verification record "
            "for the accepted kernel",
            f"{problem_key} accepted kernel has no verification record; "
            "it will not be profiled",
        )
    record["verify_status"] = "verified"
    record["record_path"] = _rel(exp_dir, verify)
    record["bench"] = _bench_case(verify_record, case)
    if verify_record.get("kernel_sha256") != record["kernel_sha256"]:
        record["verify_status"] = "hash_mismatch"
        return _fail_record(
            record,
            "accepted",
            "verify",
            "verification record describes a different kernel",
            f"{problem_key} verification hash mismatch",
        )
    print(f"{problem_key} accepted and verified "
          f"(sha256 {record['kernel_sha256'][:12]}...)")
    return True


def _stage_optimize(
    exp_dir: Path, manifest: dict, name: str, cfg: dict, budget: int
) -> bool:
    problem_rec = manifest["problems"][name]
    variant_key = f"rounds_{budget}"
    stage_root = exp_dir / "problems" / name / f"case_{cfg['case']}" / variant_key
    problem_dir = stage_root / name
    problem_dir.mkdir(parents=True, exist_ok=True)
    env = _stage_env(
        exp_dir,
        stage_root,
        cfg["optimization_model"],
        cfg.get("optimization_reasoning_effort"),
    )

    baseline = exp_dir / problem_rec["generated"]["kernel_path"]
    baseline_sha256 = problem_rec["generated"]["kernel_sha256"]
    # Seed the isolated results root with the exact generated kernel: the
    # optimizer reads final_kernel.py from its RESULTS_MOUNT, and the
    # copy is hash-checked so every budget provably starts from the same
    # source (the copy also stays beside the result, making each
    # variant's input and output inspectable together).
    staged_baseline = problem_dir / IMPL_ARTIFACTS["kernel"]["kernel"]
    shutil.copy2(baseline, staged_baseline)
    if sha256_file(staged_baseline) != baseline_sha256:
        problem_rec.setdefault("variants", {})[variant_key] = _new_variant_record(
            status="hash_mismatch",
            rounds_requested=budget,
            source_kernel_path=_rel(exp_dir, staged_baseline),
            source_kernel_sha256=baseline_sha256,
            failure={
                "stage": "stage",
                "reason": "staged baseline does not match the generated kernel",
            },
        )
        print(f"WARNING: [{name}/{variant_key}] staged baseline hash mismatch")
        return False

    ka_common.print_banner(
        f"[{name}/{variant_key}] optimizing (budget {budget} rounds, "
        f"case {cfg['case']})"
    )
    result = subprocess.run(
        [
            sys.executable,
            str(_script_path(GENERATE_SCRIPT)),
            "optimize",
            name,
            "--case",
            str(cfg["case"]),
            "--rounds",
            str(budget),
            "--workers",
            str(cfg["workers"]),
            "--test-timeout-s",
            str(cfg["test_timeout_s"]),
        ],
        env=env,
    )
    summary_path = problem_dir / IMPL_ARTIFACTS["optimized"]["summary"]
    summary = load_json_object(summary_path) or {}
    record = _new_variant_record(
        rounds_requested=budget,
        rounds_completed=(summary.get("manager_result") or {}).get(
            "total_rounds"
        ),
        source_kernel_path=_rel(exp_dir, staged_baseline),
        source_kernel_sha256=baseline_sha256,
        summary_path=_rel(exp_dir, summary_path)
        if summary_path.is_file()
        else None,
        speedup=summary.get("speedup"),
        acceptance={
            key: summary.get(key)
            for key in ("source_case_ms", "candidate_case_ms")
        },
        sessions=_sessions(exp_dir, problem_dir, "optimize_session_*"),
    )
    problem_rec.setdefault("variants", {})[variant_key] = record
    problem_key = f"[{name}/{variant_key}]"

    if result.returncode != 0 and not summary:
        return _fail_record(
            record,
            "failed",
            "optimization",
            f"generate-kernel.py optimize exited {result.returncode}",
            f"{problem_key} optimization run failed",
        )
    if not summary.get("success"):
        # A completed attempt whose candidate was not accepted (failed
        # test, error, or no speedup): the outcome and the session are
        # preserved and reported; any previously accepted kernel in
        # another variant directory is never substituted.
        reason = summary.get("reason") or "no accepted kernel"
        return _fail_record(
            record,
            "rejected",
            "acceptance",
            reason,
            f"{problem_key} no kernel accepted: {reason}",
        )
    return _accept_optimized_kernel(
        exp_dir, problem_dir, problem_key, record, summary, cfg["case"]
    )


