@contextlib.contextmanager
def _experiment_lock(exp_dir: Path):
    """Serialize manifest-mutating commands per experiment (the same flock
    discipline as generate-kernel.py's _results_lock: flock() is per open
    file description, so this blocks across processes sharing the results
    mount)."""
    with _exclusive_lock(exp_dir / ".experiment.lock"):
        yield


def _require_terminal(manifest: dict, action: str) -> None:
    """Only a terminal experiment may gain artifacts.

    A running experiment rewrites its manifest underneath us; "failed" is
    terminal too, because a crashed run's verified variants and captures
    are still valid records to measure against.
    """
    status = manifest.get("status")
    if status not in ("completed", "partial", "failed"):
        raise SystemExit(
            f"ERROR: experiment {manifest['experiment_id']!r} has status "
            f"{status!r}; {action} can only be added once an experiment is "
            "completed, partial, or failed"
        )


