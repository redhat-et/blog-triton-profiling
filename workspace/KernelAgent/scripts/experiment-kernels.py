def _fail_record(
    record: dict, status: str, stage: str, reason: str, message: str
) -> bool:
    """Mark a stage record failed and print its one-line warning; always
    returns False, so a failure branch is `return _fail_record(...)`."""
    record["status"] = status
    record["failure"] = {"stage": stage, "reason": reason}
    print(f"WARNING: {message}")
    return False


def _sessions(exp_dir: Path, stage_dir: Path, pattern: str) -> list[str]:
    """A stage's session directories, relative to the experiment root."""
    return sorted(_rel(exp_dir, p) for p in stage_dir.glob(pattern))


def _verify_stage_kernel(
    env: dict,
    name: str,
    verify_path: Path,
    timeout_s: int,
    kernel_sha256: str,
    *,
    impl: str | None = None,
    kernel: Path | None = None,
    label: str | None = None,
) -> tuple[str, str | None, dict | None]:
    """Spawn generate-kernel.py verify for one staged kernel and read the
    record it published.

    Returns (outcome, reason, record): outcome is "verified", "failed"
    (the subprocess exited nonzero or published no record — reason
    carries the exit code, or the record's own stage/reason when it got
    that far), or "hash_mismatch" (the record describes a kernel other
    than kernel_sha256). record is the parsed verification record (None
    when missing or malformed), for callers that keep the record path
    even on a failed attribution. Callers map the outcome onto their own
    record fields — generation records a status, add-baseline abandons
    the stage.
    """
    cmd = [sys.executable, str(_script_path(GENERATE_SCRIPT)), "verify", name]
    if kernel is not None:
        cmd += ["--kernel", str(kernel), "--label", label]
    else:
        cmd += ["--impl", impl]
    cmd += ["--test-timeout-s", str(timeout_s)]
    result = subprocess.run(cmd, env=env)
    verify_record = load_json_object(verify_path)
    if result.returncode != 0 or not verify_path.is_file():
        if (verify_record or {}).get("success") is False:
            return (
                "failed",
                f"verification failed ({verify_record.get('stage')}: "
                f"{verify_record.get('reason')})",
                verify_record,
            )
        return "failed", f"verification exited {result.returncode}", verify_record
    if (verify_record or {}).get("kernel_sha256") != kernel_sha256:
        return (
            "hash_mismatch",
            "verification record describes a different kernel",
            verify_record,
        )
    return "verified", None, verify_record


def _stage_generate(
    exp_dir: Path, manifest: dict, name: str, cfg: dict
) -> bool:
    problem_rec = manifest["problems"][name]
    stage_root = exp_dir / "problems" / name / "generated"
    problem_dir = stage_root / name
    env = _stage_env(
        exp_dir,
        stage_root,
        cfg["generation_model"],
        cfg.get("generation_reasoning_effort"),
    )
    record = _new_generated_record(cfg)
    problem_rec["generated"] = record

    ka_common.print_banner(f"[{name}] generating the baseline kernel")
    result = subprocess.run(
        [
            sys.executable,
            str(_script_path(GENERATE_SCRIPT)),
            "generate",
            name,
            "--workers",
            str(cfg["workers"]),
            "--rounds",
            str(cfg["generation_rounds"]),
            "--test-timeout-s",
            str(cfg["test_timeout_s"]),
        ],
        env=env,
    )
    kernel = problem_dir / IMPL_ARTIFACTS["kernel"]["kernel"]
    summary = problem_dir / IMPL_ARTIFACTS["kernel"]["summary"]
    if result.returncode != 0 or not kernel.is_file():
        return _fail_record(
            record,
            "generation_failed",
            "generation",
            f"generate-kernel.py exited {result.returncode}",
            f"[{name}] baseline generation failed; "
            "skipping its optimizations and captures",
        )
    record.update(
        {
            "status": "generated",
            "kernel_path": _rel(exp_dir, kernel),
            "kernel_sha256": sha256_file(kernel),
            "summary_path": _rel(exp_dir, summary)
            if summary.is_file()
            else None,
        }
    )
    record["rounds_completed"] = (load_json_object(summary) or {}).get(
        "rounds_used"
    )
    record["sessions"] = _sessions(exp_dir, problem_dir, "session_*")

    print(f"[{name}] verifying the generated kernel")
    verify = problem_dir / IMPL_ARTIFACTS["kernel"]["record"]
    outcome, reason, verify_record = _verify_stage_kernel(
        env,
        name,
        verify,
        cfg["test_timeout_s"],
        record["kernel_sha256"],
        impl="kernel",
    )
    if outcome != "verified":
        return _fail_record(
            record,
            "verify_failed" if outcome == "failed" else "hash_mismatch",
            "verify",
            reason,
            f"[{name}] generated kernel failed verification; "
            "it will not be optimized or profiled",
        )
    record["record_path"] = _rel(exp_dir, verify)
    record["bench"] = _bench_case(verify_record, cfg["case"])
    record["status"] = "verified"
    print(f"[{name}] baseline verified "
          f"(sha256 {record['kernel_sha256'][:12]}...)")
    return True


