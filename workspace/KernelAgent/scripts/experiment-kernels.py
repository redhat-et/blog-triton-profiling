def _parse_stage_spec(spec: str | None) -> tuple[str | None, str | None]:
    """A stage's OPENAI_MODEL[:EFFORT] spec as (model, effort), either None when
    omitted. The suffix is an effort only when it is low / medium / high,
    so a colon-bearing model id (an Ollama tag, a local-server id) passes
    through whole."""
    text = (spec or "").strip()
    if not text:
        return None, None
    model, _, suffix = text.rpartition(":")
    suffix = suffix.strip().lower()
    if suffix not in REASONING_EFFORT_LEVELS:
        return text, None
    return (model.strip() or None), suffix


def _resolve_stage(
    spec: str | None,
) -> tuple[str, str | None, str | None]:
    """One stage's effective (backend, model, effort): an explicit
    per-stage model or effort wins; the omitted part inherits the
    run-wide OPENAI_MODEL / KA_REASONING_EFFORT. The backend is inferred
    from the resolved model id exactly as the entrypoint infers the
    run-wide one (claude-* means the Anthropic API unless
    OPENAI_BASE_URL points at an OpenAI-compatible server)."""
    model, effort = _parse_stage_spec(spec)
    model = model or (os.environ.get("OPENAI_MODEL") or "").strip() or None
    effort = effort or validate_reasoning_effort(
        os.environ.get("KA_REASONING_EFFORT"), "KA_REASONING_EFFORT"
    )
    return infer_llm_backend(model), model, effort


def _validate_stage_llm(stage: str, backend: str, model: str | None) -> None:
    """Fail the whole run before anything is created when a stage's LLM
    cannot possibly work (mirrors the Makefile's _ka_require_llm, which
    only sees the run-wide model)."""
    if backend == "anthropic" and not (
        os.environ.get("ANTHROPIC_API_KEY") or ""
    ).strip():
        raise SystemExit(
            f"ERROR: the {stage} stage's model {model!r} uses the "
            "anthropic backend; set ANTHROPIC_API_KEY (or point "
            "OPENAI_BASE_URL at an OpenAI-compatible server serving it)"
        )
    if backend == "openai" and not model:
        raise SystemExit(
            f"ERROR: the {stage} stage has no model: set --{stage} "
            "OPENAI_MODEL[:EFFORT] (or the run-wide OPENAI_MODEL)"
        )
    if backend == "openai" and not (
        os.environ.get("OPENAI_API_KEY") or ""
    ).strip():
        raise SystemExit(
            f"ERROR: the {stage} stage's model {model!r} uses the openai "
            "backend; set OPENAI_API_KEY (any non-empty value works for "
            "local servers)"
        )


def _stage_env(
    exp_dir: Path,
    results_root: Path,
    model: str | None = None,
    reasoning_effort: str | None = None,
) -> dict:
    """Subprocess environment for one experiment stage: the snapshot is
    always the problem source, and RESULTS_MOUNT redirects the stage's
    artifacts into its own isolated root (generate-kernel.py writes
    results under RESULTS_MOUNT/<problem>). model routes the stage
    (OPENAI_MODEL, with LLM_BACKEND inferred from the id; a base URL the
    entrypoint defaulted is dropped for an Anthropic stage) and
    reasoning_effort overrides the run-wide KA_REASONING_EFFORT when the
    experiment resolved per-stage values; everything else — LLM
    credentials, KA_GPU_TARGET, KA_GPU_NAME — passes through
    unchanged."""
    env = {
        **os.environ,
        "PROBLEMS_HOME": str(exp_dir / "specs"),
    }
    if results_root is not None:
        env["RESULTS_MOUNT"] = str(results_root)
    if model:
        backend = infer_llm_backend(model)
        env["OPENAI_MODEL"] = model
        env["LLM_BACKEND"] = backend
        if (
            backend == "anthropic"
            and env.get("KA_OPENAI_BASE_URL_DEFAULTED") == "1"
        ):
            # The entrypoint's default public URL is not a server for this
            # stage; LLM_BACKEND=anthropic is the routing decision.
            env.pop("OPENAI_BASE_URL", None)
    if reasoning_effort:
        env["KA_REASONING_EFFORT"] = reasoning_effort
    return env


def _bench_case(record: dict | None, case_index: int) -> dict | None:
    """The selected case's benchmark entry from a parsed verification
    record (the fixed bench.py timing: the only timing that runs the
    exact shapes and dtype of the case)."""
    entry = find_bench_case((record or {}).get("benchmark"), case_index)
    if entry is None:
        return None
    return {
        key: entry.get(key)
        for key in (
            "kernel_ms",
            "ref_ms",
            "speedup",
            "kernel_tflops",
            "ref_tflops",
        )
    }


