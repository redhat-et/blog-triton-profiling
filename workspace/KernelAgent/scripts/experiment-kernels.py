def _script_path(name: str) -> Path:
    """A sibling CLI script by name: next to this file both in the
    repository (workspace/KernelAgent/scripts/) and in the image
    (/usr/local/bin), with a PATH lookup as the fallback."""
    sibling = SCRIPT_DIR / name
    if sibling.is_file():
        return sibling
    found = shutil.which(name)
    if found:
        return Path(found)
    raise SystemExit(f"ERROR: cannot locate {name} beside {SCRIPT_DIR}")


def _rel(exp_dir: Path, path: Path) -> str:
    """A manifest path, stored relative to the experiment root so the tree
    stays valid if the results mount moves."""
    return os.path.relpath(path, exp_dir)


def _maybe_rel(exp_dir: Path, path: str) -> str:
    """Relativize a path recorded by a subprocess when it lives inside the
    experiment (profile-kernel.py records absolute paths, which inside
    the container are only meaningful there); anything outside the
    experiment keeps its absolute form."""
    candidate = Path(path)
    if not candidate.is_absolute():
        return path
    exp_root = exp_dir.resolve()
    resolved = candidate.resolve()
    if resolved.is_relative_to(exp_root):
        return os.path.relpath(resolved, exp_root)
    return path


