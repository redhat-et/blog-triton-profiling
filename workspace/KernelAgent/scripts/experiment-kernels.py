def _probe(cmd: list[str], parse, timeout: int = 60, default=None):
    """Run a best-effort probe child and parse its stdout; default when
    the child cannot run, exits nonzero, or its output cannot be parsed."""
    try:
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout
        )
    except (OSError, subprocess.TimeoutExpired):
        return default
    if result.returncode != 0:
        return default
    try:
        return parse(result.stdout or "")
    except (json.JSONDecodeError, TypeError, ValueError):
        return default


def _first_line(stdout: str) -> str | None:
    for line in stdout.splitlines():
        line = line.strip()
        if line:
            return line
    return None


def _probe_text(cmd: list[str], timeout: int = 60) -> str | None:
    return _probe(cmd, _first_line, timeout)


def _probe_json(cmd: list[str]) -> dict | None:
    return _probe(cmd, json.loads, timeout=120)


def _probe_cuda_environment() -> tuple[dict | None, dict | None]:
    """(logical CUDA device 0, torch/triton versions) from one isolated
    child process, so this one never initializes CUDA and pays the torch
    import at most once. The launcher and the entry validation are
    ka_common's; the child inherits the environment unchanged
    (CUDA_VISIBLE_DEVICES filtering included), and
    its first device is logical device 0 — the device the fixed
    benchmarks and the profilers use.

    The two halves fail independently at the parsing layer: device is
    None when the probe cannot run, CUDA reports no visible device, or
    the device line is missing or malformed; versions is None when the
    versions line is missing or malformed (a crashed child yields
    (None, None) — in practice a crash means the torch import itself
    failed, so the versions were unavailable anyway).
    """
    devices, versions = ka_common._run_cuda_probe()
    device = None
    if devices:
        entry = ka_common._probe_device_entry(devices[0])
        if entry is not None:
            device = {
                "name": entry["name"],
                "uuid": entry["uuid"],
                "memory_bytes": entry["total_memory"],
            }
    return device, versions


def _smi_gpu_inventory() -> list[dict] | None:
    """Every physical GPU nvidia-smi reports (the shared ka_common query
    and CSV parser). None when nvidia-smi cannot run. nvidia-smi ignores
    CUDA_VISIBLE_DEVICES, so these rows describe the whole host — never
    the selection itself."""
    rows = ka_common._smi_inventory(
        ("name", "uuid", "driver_version", "memory.total"),
    )
    if rows is None:
        return None
    inventory = []
    for name, uuid, driver, memory in rows:
        if name and uuid:
            inventory.append(
                {
                    "name": name,
                    "uuid": uuid,
                    "driver_version": driver,
                    "memory_total": memory,
                }
            )
    return inventory or None


def _repo_root() -> Path | None:
    """The repository containing this script, if running from a checkout
    (the image's /usr/local/bin copies have none)."""
    current = SCRIPT_DIR
    for _ in range(5):
        if (current / ".git").exists():
            return current
        if current.parent == current:
            break
        current = current.parent
    return None


def _git_status(repo: Path) -> dict | None:
    """(commit, dirty) of the repository, or None when git cannot run.
    One git call carries both facts: porcelain=v2's header reports the
    HEAD oid, and any non-header line means a dirty tree."""
    try:
        status = subprocess.run(
            [
                "git",
                "-C",
                str(repo),
                "status",
                "--porcelain=v2",
                "--branch",
            ],
            capture_output=True,
            text=True,
            timeout=60,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if status.returncode != 0:
        return None
    commit = None
    dirty = False
    for line in (status.stdout or "").splitlines():
        if line.startswith("# branch.oid "):
            commit = line.split()[-1]
        elif line and not line.startswith("#"):
            dirty = True
    if commit and commit != "(initial)":
        return {"commit": commit, "dirty": dirty}
    return None


_KERNELAGENT_VERSION_PROBE = (
    "import json; from importlib.metadata import version; "
    "print(json.dumps({'v': version('KernelAgent')}))"
)


def _collect_environment() -> dict:
    """Best-effort hardware/software record; every field is None when its
    probe cannot run, so an unusual host never fails an experiment. The
    independent probes run concurrently — the CUDA probe pays a full
    torch import in its child and each version probe pays a process
    spawn, so serializing them wastes several seconds at experiment
    creation for no benefit."""
    env: dict = {"collected_at": datetime.now().isoformat()}

    env["cuda_visible_devices"] = os.environ.get("CUDA_VISIBLE_DEVICES")
    env["cuda_device_order"] = os.environ.get("CUDA_DEVICE_ORDER")
    repo = _repo_root()
    with ThreadPoolExecutor(max_workers=7) as pool:
        futures = {
            "cuda": pool.submit(_probe_cuda_environment),
            "smi": pool.submit(_smi_gpu_inventory),
            "nvcc": pool.submit(_probe_text, ["nvcc", "--version"]),
            "kernelagent": pool.submit(
                _probe_json,
                [sys.executable, "-c", _KERNELAGENT_VERSION_PROBE],
            ),
            "ncu": pool.submit(ka_common.probe_tool_version, "ncu"),
            "nsys": pool.submit(ka_common.probe_tool_version, "nsys"),
            "git": (
                pool.submit(_git_status, repo) if repo is not None else None
            ),
        }
        cuda_device, versions = futures["cuda"].result()
        smi_rows = futures["smi"].result()
        nvcc = futures["nvcc"].result()
        env["kernelagent"] = (futures["kernelagent"].result() or {}).get("v")
        env["ncu_version"] = futures["ncu"].result()
        env["nsys_version"] = futures["nsys"].result()
        git = futures["git"].result() if futures["git"] is not None else None

    gpu: dict = {
        "name": None,
        "uuid": None,
        "driver_version": None,
        "memory_total": None,
    }
    if cuda_device is not None:
        gpu["name"] = cuda_device["name"]
        gpu["uuid"] = cuda_device["uuid"]
        if cuda_device["memory_bytes"] is not None:
            gpu["memory_total"] = (
                f"{cuda_device['memory_bytes'] // (1024 ** 2)} MiB"
            )
        # Cross-check the CUDA identity against the host inventory; the
        # driver version and smi-formatted details come from the matching
        # row only — an unmatched UUID leaves them unset rather than
        # guessing from a row that may describe a different GPU.
        row = None
        if smi_rows and cuda_device["uuid"]:
            row = next(
                (r for r in smi_rows if r["uuid"] == cuda_device["uuid"]), None
            )
        if row is not None:
            gpu["driver_version"] = row["driver_version"]
            gpu["memory_total"] = row["memory_total"]
    env["gpu"] = gpu

    cuda = None
    if nvcc:
        match = re.search(r"release ([0-9.]+)", nvcc)
        cuda = match.group(1) if match else nvcc
    env["cuda"] = cuda or os.environ.get("CUDA_VERSION")

    env["torch"] = None
    env["triton"] = None
    # The versions come from the same probe child as the device (one
    # torch import, not two); a broken triton install still records the
    # torch and CUDA versions, with triton left null.
    if versions:
        env.update(
            {"torch": versions.get("torch"), "triton": versions.get("triton")}
        )
        if not env["cuda"]:
            env["cuda"] = versions.get("cuda")

    env["python"] = sys.version.split()[0]
    env["platform"] = platform.platform()
    env["git"] = git
    return env


