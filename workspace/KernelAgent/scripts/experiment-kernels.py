def _parse_word_list(text: str, what: str) -> list[str]:
    items = [item for item in re.split(r"[,\s]+", text.strip()) if item]
    if not items:
        raise SystemExit(f"ERROR: {what} must name at least one entry")
    seen: list[str] = []
    for item in items:
        if item not in seen:
            seen.append(item)
    return seen


def _parse_rounds(text: str) -> list[int]:
    """Optimization round budgets: positive ints, deduplicated in order."""
    words = _parse_word_list(text, "--opt-rounds")
    rounds: list[int] = []
    for word in words:
        try:
            value = int(word)
        except ValueError:
            raise SystemExit(
                f"ERROR: optimization rounds must be integers (got {word!r})"
            )
        if value < 1:
            raise SystemExit(
                f"ERROR: optimization rounds must be >= 1 (got {value})"
            )
        if value not in rounds:
            rounds.append(value)
    return rounds


def _parse_profilers(text: str) -> list[str]:
    profilers = _parse_word_list(text, "--profilers")
    for name in profilers:
        if name not in SUPPORTED_PROFILERS:
            raise SystemExit(
                f"ERROR: unsupported profiler {name!r} "
                f"(choose from {', '.join(SUPPORTED_PROFILERS)})"
            )
    return profilers


