def _generate_report(exp_dir: Path) -> bool:
    """Render comparison.md/json via report-experiment.py (loaded, not
    spawned, so the report runs in this dependency-free process)."""
    try:
        report_mod = ka_common._load_module(
            "report_experiment", _script_path(REPORT_SCRIPT), register=True
        )
        out = report_mod.generate_report(exp_dir)
    except Exception as exc:  # noqa: BLE001 - report failure (including a
        # report module that cannot even be loaded) must not discard the
        # experiment's artifacts
        print(f"WARNING: report generation failed: {exc}", file=sys.stderr)
        return False
    print(f"Report: {out}")
    return True


def _finish_with_report(exp_dir: Path, manifest: dict, ok: bool) -> bool:
    """Render the report and record the terminal manifest state.

    The caller persists its terminal status first — the report reloads
    manifest.json from disk, so rendering it against a persisted
    "running" status would bake that into both comparison files. A failed
    render downgrades the experiment to "partial" with no report record;
    a successful one records where the report landed. Every mutating
    command (run, profile, add-baseline) ends this way.
    """
    if _generate_report(exp_dir):
        manifest["report"] = {
            "path": "reports/comparison.md",
            "generated_at": datetime.now().isoformat(),
        }
    else:
        ok = False
        manifest["status"] = "partial"
        manifest["report"] = None
    _save_manifest(exp_dir, manifest)
    return ok


def _capture_args(
    args, *, profilers_optional: bool = False
) -> tuple[list[str], int, int]:
    """A command's capture settings, validated before anything is
    created: the profilers to run, and the measured/warmup iterations.
    profilers_optional mirrors _add_profilers_args' profilers_default=None
    (add-baseline): there an empty --profilers means verify and record
    only, while run/profile require at least one. (--ncu-set passes
    through as-is.)"""
    if profilers_optional and not (args.profilers or "").strip():
        profilers = []
    else:
        profilers = _parse_profilers(args.profilers)
    profile_iters = _positive_int(args.profile_iters, "--profile-iters")
    profile_warmup = _positive_int(args.profile_warmup, "--profile-warmup")
    return profilers, profile_iters, profile_warmup


