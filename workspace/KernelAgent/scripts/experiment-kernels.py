def cmd_run(args) -> int:
    problems = _parse_word_list(args.problems, "--problems")
    available = available_problems(PROBLEMS_HOME)
    for name in problems:
        if name not in available:
            raise SystemExit(
                f"ERROR: unknown problem {name!r} (choose from "
                f"{', '.join(available)})"
            )
    opt_rounds = _parse_rounds(args.opt_rounds)
    profilers, profile_iters, profile_warmup = _capture_args(args)
    workers = _positive_int(args.workers, "--workers")
    generation_rounds = _positive_int(
        args.generation_rounds, "--generation-rounds"
    )

    # Validate every problem's case before touching disk: a bad case must
    # fail the whole run before any generation session exists.
    case_specs = {}
    for name in problems:
        spec = ka_common._load_spec(
            PROBLEMS_HOME, name, prefix="exp_spec_", register=True
        )
        cases = list(spec.BENCH_CASES)
        if not 0 <= args.case < len(cases):
            raise SystemExit(
                f"ERROR: --case must be in 0..{len(cases) - 1} for {name} "
                f"(got {args.case})"
            )
        case_specs[name] = str(cases[args.case])

    # Resolve each stage's LLM before touching disk: an unusable backend
    # or a missing credential must fail the whole run before any
    # generation session exists.
    generation_backend, generation_model, generation_effort = _resolve_stage(
        args.generation
    )
    (
        optimization_backend,
        optimization_model,
        optimization_effort,
    ) = _resolve_stage(args.optimization)
    _validate_stage_llm("generation", generation_backend, generation_model)
    _validate_stage_llm(
        "optimization", optimization_backend, optimization_model
    )

    exp_id = args.experiment or _new_experiment_id()
    safe_name_component(exp_id, "experiment id")
    exp_dir = experiments_home(RESULTS_MOUNT) / exp_id
    # mkdir with exist_ok=False claims the id atomically: a second run with
    # the same id (or two concurrent runs) can never interleave.
    try:
        exp_dir.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        raise SystemExit(
            f"ERROR: experiment {exp_id!r} already exists at {exp_dir}; "
            "choose a new id (additional profiling of an existing "
            "experiment: 'experiment-kernels.py profile')"
        )

    ka_common.print_banner(
        f"KernelAgent — comparison experiment: {exp_id}"
    )
    print(f"Experiment dir: {exp_dir}")
    print(f"Problems:       {', '.join(problems)}")
    print(f"Case:           {args.case}")
    print(f"Generation:     {workers} worker(s), {generation_rounds} rounds")
    print(f"Optimization:   budgets {opt_rounds}")
    print(f"Generation LLM: {generation_backend} / {generation_model}"
          + (f" / {generation_effort}" if generation_effort else ""))
    print(f"Optimization LLM: {optimization_backend} / {optimization_model}"
          + (f" / {optimization_effort}" if optimization_effort else ""))
    print(f"Profilers:      {', '.join(profilers)}")
    print(f"EXPERIMENT_ID: {exp_id}")

    manifest = {
        "schema_version": MANIFEST_SCHEMA_VERSION,
        "experiment_id": exp_id,
        "created_at": datetime.now().isoformat(),
        "updated_at": None,
        "status": "running",
        "configuration": {
            "problems": problems,
            "case": args.case,
            "generation_rounds": generation_rounds,
            "optimization_rounds": opt_rounds,
            "workers": workers,
            "test_timeout_s": args.test_timeout_s,
            "llm_backend": infer_llm_backend(os.environ.get("OPENAI_MODEL")),
            "generation_backend": generation_backend,
            "generation_model": generation_model,
            "generation_reasoning_effort": generation_effort,
            "optimization_backend": optimization_backend,
            "optimization_model": optimization_model,
            "optimization_reasoning_effort": optimization_effort,
            "profilers": profilers,
            "profile_iters": profile_iters,
            "profile_warmup": profile_warmup,
            "ncu_set": args.ncu_set,
        },
        "environment": _collect_environment(),
        "problems": {
            name: {
                "status": None,
                "case": args.case,
                "case_spec": case_specs[name],
                "spec_files": None,
                "generated": None,
                "variants": {},
            }
            for name in problems
        },
        "capture_batches": [],
        "report": None,
    }
    spec_hashes, shared_harness = _snapshot_specs(exp_dir, problems)
    for name in problems:
        manifest["problems"][name]["spec_files"] = spec_hashes[name]
    manifest["shared_harness"] = shared_harness
    _atomic_write_json(
        exp_dir / "environment.json", manifest["environment"]
    )
    _save_manifest(exp_dir, manifest)

    failures = 0
    # An unanticipated crash in a stage or capture batch must not wedge
    # the persisted manifest at "running": that status blocks
    # add-baseline until an operator edits manifest.json by
    # hand. Persist a terminal "failed" status first, then re-raise so
    # the crash stays loud — the exception is a bug to fix, not a quiet
    # "partial" to attribute the run's outcome to.
    try:
        for name in problems:
            if not _stage_generate(exp_dir, manifest, name, manifest["configuration"]):
                failures += 1
                manifest["problems"][name]["status"] = manifest["problems"][name][
                    "generated"
                ]["status"]
                _save_manifest(exp_dir, manifest)
                continue
            manifest["problems"][name]["status"] = "verified"
            _save_manifest(exp_dir, manifest)
            for budget in opt_rounds:
                if not _stage_optimize(
                    exp_dir, manifest, name, manifest["configuration"], budget
                ):
                    failures += 1
                _save_manifest(exp_dir, manifest)

        if profilers and any(
            _profileable_variants(rec)
            for rec in manifest["problems"].values()
        ):
            if not _run_capture_batch(
                exp_dir,
                manifest,
                profilers,
                profile_iters,
                profile_warmup,
                args.ncu_set,
                None,
            ):
                failures += 1
            _save_manifest(exp_dir, manifest)
    except Exception:
        manifest["status"] = "failed"
        _save_manifest(exp_dir, manifest)
        raise

    # The terminal status is persisted before the report renders — the
    # report reloads manifest.json from disk, so rendering it while the
    # persisted status is still "running" would bake that into both
    # comparison files.
    manifest["status"] = "completed" if failures == 0 else "partial"
    # Profile and add-baseline become legal the moment the status is
    # terminal; hold the lock through the report's final save so their
    # appended batches are not overwritten by this in-memory copy.
    with _experiment_lock(exp_dir):
        _save_manifest(exp_dir, manifest)
        if not _finish_with_report(exp_dir, manifest, failures == 0):
            failures += 1
    print("=" * 72)
    print(f"Experiment {exp_id}: {manifest['status']} "
          f"({failures} failed stage(s))")
    print(f"Manifest: {exp_dir / 'manifest.json'}")
    print(f"EXPERIMENT_ID: {exp_id}")
    return 0 if failures == 0 else 1


def cmd_profile(args) -> int:
    exp_dir = resolve_experiment(RESULTS_MOUNT, args.experiment)
    # One writer at a time per experiment: the capture batch below appends
    # to the manifest, which must not interleave with another mutating
    # command (profile, add-baseline) holding a stale copy.
    with _experiment_lock(exp_dir):
        return _profile(exp_dir, args)


def _profile(exp_dir: Path, args) -> int:
    manifest = _load_manifest(exp_dir)
    _require_terminal(manifest, "captures")
    profilers, profile_iters, profile_warmup = _capture_args(args)

    known = list(manifest["problems"])
    problems_filter = None
    if args.problems:
        problems_filter = _parse_word_list(args.problems, "--problems")
        for name in problems_filter:
            if name not in known:
                raise SystemExit(
                    f"ERROR: experiment {manifest['experiment_id']!r} has no "
                    f"problem {name!r} (it has {', '.join(known)})"
                )

    ka_common.print_banner(
        f"KernelAgent — additional captures: {manifest['experiment_id']}"
    )
    print(f"Experiment dir: {exp_dir}")
    print(f"Profilers:      {', '.join(profilers)}")

    ok = _run_capture_batch(
        exp_dir,
        manifest,
        profilers,
        profile_iters,
        profile_warmup,
        args.ncu_set,
        problems_filter,
    )
    # Persist the terminal status before the report renders (it reloads
    # manifest.json from disk), matching cmd_run's ordering.
    manifest["status"] = "partial" if not ok else manifest.get("status")
    _save_manifest(exp_dir, manifest)
    ok = _finish_with_report(exp_dir, manifest, ok)
    return 0 if ok else 1


def _validate_baseline_label(label: str, problem_rec: dict) -> None:
    """Baseline labels share the variant namespace (capture-batch keys,
    report rows), so a label must be path-safe and must not collide with
    the generated/rounds variants. A label already recorded as a baseline
    is handled by _add_baseline: the same source is a no-op, and a
    different source is verified before the collision is reported, so a
    kernel-contract failure is never hidden by the label check."""
    validate_label(label)
    if label == GENERATED_VARIANT or variant_budget(label) is not None:
        raise SystemExit(
            f"ERROR: baseline label {label!r} collides with the variant "
            "naming scheme (generated, rounds_<N>)"
        )
    if label in (problem_rec.get("variants") or {}):
        raise SystemExit(
            f"ERROR: baseline label {label!r} collides with an existing "
            "variant of this problem"
        )


def cmd_add_baseline(args) -> int:
    exp_dir = resolve_experiment(RESULTS_MOUNT, args.experiment)
    # One writer at a time per experiment: the label-collision checks and
    # the manifest updates below must not interleave with another
    # add-baseline (or a profile run appending a capture batch).
    with _experiment_lock(exp_dir):
        return _add_baseline(exp_dir, args)


def _add_baseline(exp_dir: Path, args) -> int:
    manifest = _load_manifest(exp_dir)
    exp_id = manifest["experiment_id"]
    name = args.problem
    known = list(manifest["problems"])
    if name not in known:
        raise SystemExit(
            f"ERROR: experiment {exp_id!r} has no problem {name!r} "
            f"(it has {', '.join(known)})"
        )
    _require_terminal(manifest, "baselines")
    problem_rec = manifest["problems"][name]
    label = args.label
    _validate_baseline_label(label, problem_rec)
    existing = (problem_rec.get("baselines") or {}).get(label)

    source = Path(args.kernel)
    if not source.is_file():
        raise SystemExit(f"ERROR: kernel file {source} not found")

    # Re-running with the same source and label is a no-op. A different
    # source is verified below before the label collision is reported, so
    # a kernel-contract failure surfaces instead of the collision.
    source_sha256 = sha256_file(source)
    if existing and existing.get("kernel_sha256") == source_sha256:
        print(
            f"[{name}/{label}] already recorded with this source "
            f"(sha256 {source_sha256[:12]}...); nothing to do"
        )
        return 0

    # Validate every capture setting before touching disk (the same
    # fail-fast rule as cmd_run): a bad flag must fail before the stage
    # directory exists.
    profilers, profile_iters, profile_warmup = _capture_args(
        args, profilers_optional=True
    )

    ka_common.print_banner(
        f"KernelAgent — add baseline: {exp_id}/{name}/{label}"
    )
    print(f"Experiment dir: {exp_dir}")
    print(f"Kernel:         {source}")
    print(
        "Profilers:      "
        + (", ".join(profilers) if profilers else "none (record only)")
    )

    # Stage layout mirrors the other stages: problems/<P>/baselines/<label>
    # is this baseline's results root, and the verify subprocess writes
    # under RESULTS_MOUNT/<problem>/ — hence the <label>/<P> nesting.
    stage_root = exp_dir / "problems" / name / "baselines" / label
    if existing:
        # The recorded baseline owns its stage directory. Verify a new
        # source in a temporary sibling so a failing kernel reports the
        # contract failure and leaves the recorded baseline untouched; a
        # passing source still cannot silently replace it.
        verify_root = stage_root.with_name(
            f".{label}.candidate-{secrets.token_hex(4)}"
        )
    else:
        verify_root = stage_root
    problem_dir = verify_root / name
    # mkdir with exist_ok=False claims the stage atomically (the same
    # discipline as experiment-id claiming): a repeated or concurrent
    # add-baseline for this label can never interleave.
    try:
        problem_dir.mkdir(parents=True, exist_ok=False)
    except FileExistsError:
        raise SystemExit(
            f"ERROR: baseline {label!r} already has a stage directory at "
            f"{stage_root}; remove it or choose another label"
        )

    def abandon(reason: str) -> int:
        # Nothing is recorded: a baseline that cannot be verified must
        # not appear in the manifest, the captures, or the report. When a
        # baseline with this label already exists, only the temporary
        # verification tree is removed.
        print(f"WARNING: [{name}/{label}] {reason}; nothing recorded")
        shutil.rmtree(verify_root)
        if not existing:
            # Drop the baselines/ scaffold too when this was its only
            # label, so a failed add leaves no empty directory behind
            # (rmdir on a non-empty dir raises, which is exactly the
            # guard we want).
            try:
                stage_root.parent.rmdir()
            except OSError:
                pass
        return 1

    archived = problem_dir / "kernel.py"
    shutil.copy2(source, archived)
    kernel_sha256 = sha256_file(archived)

    print(f"[{name}/{label}] verifying the external kernel")
    # Attribution: the record must describe the archived bytes that were
    # copied and hashed above (the hash-check discipline every other
    # stage applies to its kernel).
    outcome, reason, verify_record = _verify_stage_kernel(
        _stage_env(exp_dir, verify_root),
        name,
        problem_dir / f"verify_{label}.json",
        args.test_timeout_s,
        kernel_sha256,
        kernel=archived,
        label=label,
    )
    if outcome != "verified":
        return abandon(reason)
    if existing:
        shutil.rmtree(verify_root)
        raise SystemExit(
            f"ERROR: baseline {label!r} is already recorded "
            f"(sha256 {(existing.get('kernel_sha256') or '')[:12]}...); "
            "the new source verified, but a recorded baseline cannot be "
            "replaced — use a different label or a new experiment"
        )
    verify = problem_dir / f"verify_{label}.json"

    problem_rec.setdefault("baselines", {})[label] = {
        "status": "verified",
        "kind": "external",
        "label": label,
        "kernel_path": _rel(exp_dir, archived),
        "kernel_sha256": kernel_sha256,
        "source_path": args.source_path or str(args.kernel),
        "record_path": _rel(exp_dir, verify),
        "bench": _bench_case(verify_record, manifest["configuration"]["case"]),
        "added_at": datetime.now().isoformat(),
        "failure": None,
    }
    _save_manifest(exp_dir, manifest)
    print(
        f"[{name}/{label}] baseline verified "
        f"(sha256 {kernel_sha256[:12]}...)"
    )

    ok = True
    if profilers:
        if not _run_capture_batch(
            exp_dir,
            manifest,
            profilers,
            profile_iters,
            profile_warmup,
            args.ncu_set,
            None,
            {(name, label)},
        ):
            ok = False
            manifest["status"] = "partial"
        _save_manifest(exp_dir, manifest)

    # Render the report and record the terminal manifest state (the same
    # ordering as cmd_run/cmd_profile: the terminal status is persisted
    # first, because the report reloads manifest.json from disk).
    ok = _finish_with_report(exp_dir, manifest, ok)
    print(f"Manifest: {exp_dir / 'manifest.json'}")
    return 0 if ok else 1


def _add_profilers_args(parser, profilers_default: str | None = "proton") -> None:
    """Capture-batch arguments shared by every command that can profile.
    add-baseline passes profilers_default=None: no profilers means verify
    and record only, with no capture batch."""
    if profilers_default is None:
        default_help = "(default: none — verify and record only)"
    else:
        default_help = f"(default: {profilers_default})"
    parser.add_argument(
        "--profilers",
        default=profilers_default,
        help='space- or comma-separated profilers: "ncu nsys proton" '
        f"{default_help}",
    )
    parser.add_argument(
        "--profile-iters",
        type=int,
        default=10,
        help="measured iterations per capture (default: 10)",
    )
    parser.add_argument(
        "--profile-warmup",
        type=int,
        default=10,
        help="warmup iterations per capture (default: 10)",
    )
    parser.add_argument(
        "--ncu-set",
        default="basic",
        help="ncu --set value (default: basic; use detailed/full for more)",
    )


def _add_common_args(parser, with_run_settings: bool) -> None:
    """Arguments shared by run and profile; run additionally takes the
    generation/optimization settings."""
    if with_run_settings:
        parser.add_argument(
            "--problems",
            default=" ".join(available_problems(PROBLEMS_HOME)),
            help="space- or comma-separated problems (default: every "
            "problem in PROBLEMS_HOME)",
        )
        parser.add_argument(
            "--case",
            type=int,
            default=0,
            help="benchmark case index every stage targets (default: 0)",
        )
        parser.add_argument(
            "--generation-rounds",
            type=int,
            default=_env_int("KA_ROUNDS", 5),
            help="refinement-round budget for the baseline generation "
            "(default: KA_ROUNDS or 5)",
        )
        parser.add_argument(
            "--opt-rounds",
            default="5 10",
            help="space- or comma-separated optimization round budgets; "
            "each budget optimizes the same generated kernel "
            '(default: "5 10")',
        )
        parser.add_argument(
            "--generation",
            default=os.environ.get("KA_GENERATION_MODEL"),
            help="OPENAI_MODEL[:EFFORT] for the generation stage (default: "
            "KA_GENERATION_MODEL or the run-wide OPENAI_MODEL / "
            "KA_REASONING_EFFORT; the backend is inferred from the model)",
        )
        parser.add_argument(
            "--optimization",
            default=os.environ.get("KA_OPTIMIZATION_MODEL"),
            help="OPENAI_MODEL[:EFFORT] for the optimization stage (default: "
            "KA_OPTIMIZATION_MODEL or the run-wide OPENAI_MODEL / "
            "KA_REASONING_EFFORT; the backend is inferred from the model)",
        )
        parser.add_argument(
            "--workers",
            type=int,
            default=_env_int("KA_WORKERS", 1),
            help="parallel candidates for generation and optimization "
            "(default: KA_WORKERS or 1)",
        )
        parser.add_argument(
            "--test-timeout-s",
            type=int,
            default=180,
            help="per-test subprocess timeout in seconds (default: 180)",
        )
    else:
        parser.add_argument(
            "--problems",
            default=None,
            help="restrict the capture batch to these problems "
            "(default: every problem in the experiment)",
        )
    _add_profilers_args(parser)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    run_p = sub.add_parser(
        "run", help="create an experiment: generate, optimize, profile"
    )
    run_p.add_argument(
        "experiment",
        nargs="?",
        default=None,
        help="experiment id (default: auto-generated)",
    )
    _add_common_args(run_p, with_run_settings=True)
    run_p.set_defaults(func=cmd_run)

    profile_p = sub.add_parser(
        "profile", help="add a capture batch to an existing experiment"
    )
    profile_p.add_argument(
        "experiment", help="experiment id (or its directory)"
    )
    _add_common_args(profile_p, with_run_settings=False)
    profile_p.set_defaults(func=cmd_profile)

    baseline_p = sub.add_parser(
        "add-baseline",
        help="add an external kernel to an existing experiment",
    )
    baseline_p.add_argument(
        "experiment", help="experiment id (or its directory)"
    )
    baseline_p.add_argument(
        "--problem",
        required=True,
        help="the experiment problem the kernel targets",
    )
    baseline_p.add_argument(
        "--label",
        required=True,
        help="baseline name (path-safe; must not collide with variants)",
    )
    baseline_p.add_argument(
        "--kernel",
        type=Path,
        required=True,
        help="kernel source file defining a top-level kernel_function",
    )
    baseline_p.add_argument(
        "--source-path",
        default=None,
        help="original source path recorded in the manifest and report "
        "(default: the --kernel path)",
    )
    baseline_p.add_argument(
        "--test-timeout-s",
        type=int,
        default=180,
        help="per-test subprocess timeout in seconds (default: 180)",
    )
    _add_profilers_args(baseline_p, profilers_default=None)
    baseline_p.set_defaults(func=cmd_add_baseline)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
