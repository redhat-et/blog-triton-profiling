# Stage: snapshot problem specs


def _snapshot_specs(
    exp_dir: Path, problems: list[str]
) -> tuple[dict[str, dict[str, str]], dict[str, str] | None]:
    """Copy the selected problems' specs (and the shared harness) into the
    experiment. Every later stage — generation, optimization,
    verification, profiling — runs against this snapshot, so an experiment
    describes exactly the problem definitions it was created with.

    Returns the per-problem file hashes and, separately, the shared
    harness record ({file, sha256}, or None when absent) for the
    manifest's top-level ``shared_harness`` pin.
    """
    specs_dir = exp_dir / "specs"
    hashes: dict[str, dict[str, str]] = {}
    for name in problems:
        pdir = PROBLEMS_HOME / name
        dest = specs_dir / name
        dest.mkdir(parents=True, exist_ok=True)
        for fname in PROBLEM_FILES:
            shutil.copy2(pdir / fname, dest / fname)
        hashes[name] = {
            fname: sha256_file(dest / fname) for fname in PROBLEM_FILES
        }
    harness = None
    harness_src = PROBLEMS_HOME / SHARED_HARNESS
    if harness_src.is_file():
        shutil.copy2(harness_src, specs_dir / SHARED_HARNESS)
        harness = {
            "file": SHARED_HARNESS,
            "sha256": sha256_file(specs_dir / SHARED_HARNESS),
        }
    return hashes, harness


