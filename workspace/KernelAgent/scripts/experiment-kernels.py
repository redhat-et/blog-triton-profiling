#!/usr/bin/env python3
"""Run a KernelAgent comparison experiment: generate, optimize, profile.

An experiment is one self-contained tree under the results mount:

  results/experiments/<experiment-id>/
    manifest.json          The authoritative index (this file's schema)
    environment.json       GPU / driver / software versions at creation
    specs/                 Snapshot of every problem spec used (plus the
                           shared _harness.py) — later edits to the
                           repository's problem definitions cannot change
                           what an existing experiment runs
    sources/<file>         Host kernel source copied in for an add-baseline
                           run; the archived copy lives under
                           problems/<P>/baselines/<label>/
    problems/<P>/
      generated/<P>/       Generation results root for <P>: final_kernel.py,
                           generate_result.json, verify.json, session_*/
      case_<C>/rounds_<B>/<P>/
                           One independent optimization of the same
                           generated kernel with round budget B: the copied
                           baseline final_kernel.py beside the accepted
                           optimized_kernel.py (when one was accepted),
                           optimize_result.json, verify_optimized.json,
                           optimize_session_*/
      baselines/<label>/<P>/
                           One external baseline kernel added after the
                           experiment ran: the archived kernel.py beside
                           its verify_<label>.json
    captures/<capture-id>/<P>/
                           Profiler captures, one stem per
                           variant/profiler: <label>_<profiler>_case<C>.*
    reports/               comparison.md, comparison.json, source-diffs/

Every optimization budget starts from the exact same generated source
(the copied baseline is hash-checked against the generated kernel before
the optimizer runs), failed or non-improving attempts are preserved and
reported instead of silently falling back to an older kernel, and each
profiling pass runs against the archived, verified sources so capture
identity can never drift through a later run.

Three commands:

  run       Create an experiment: snapshot specs, generate one baseline
            kernel per problem, verify it, optimize it once per requested
            round budget, verify each accepted kernel, capture every
            requested profiler, and write the comparison report.
  profile   Add one capture batch to an existing experiment (no LLM
            needed): re-profile the archived sources with any subset of
            the profilers.
  add-baseline
            Add an external kernel to a finished experiment (no LLM
            needed): archive and hash it, verify it against the
            experiment's spec snapshot, record it in the manifest, and
            optionally capture the requested profilers for it alone.
            Re-adding the same source under the same label is a no-op; a
            different source is verified first, so a kernel that fails
            the problem contract reports that failure before the label
            collision, and the recorded baseline is left untouched.

Experiments are immutable once created, apart from added capture batches
and external baselines: retrying or extending the optimization means
creating a new experiment id.

Reports are regenerated by report-experiment.py, which works offline from
the manifest and saved artifacts — see that script for the report side.

Each LLM stage takes one OPENAI_MODEL[:EFFORT] spec. The suffix is a reasoning
effort only when it is low / medium / high, so colon-bearing model ids
(Ollama tags, local-server ids) pass through whole; an omitted model or
effort falls back to the run-wide OPENAI_MODEL / KA_REASONING_EFFORT, and
the stage's backend is inferred from its model id.

Usage:
  experiment-kernels.py run [experiment-id] [--problems "A B"] [--case N]
                            [--generation-rounds N] [--opt-rounds "5 10"]
                            [--generation OPENAI_MODEL[:EFFORT]]
                            [--optimization OPENAI_MODEL[:EFFORT]]
                            [--workers N] [--profilers "ncu nsys proton"]
                            [--profile-iters N] [--profile-warmup N]
                            [--ncu-set SET] [--test-timeout-s N]
  experiment-kernels.py profile <experiment-id> [--problems "A"]
                                             [--profilers "nsys proton"]
                                             [--profile-iters N] ...
  experiment-kernels.py add-baseline <experiment-id> --problem P
                                      --label NAME --kernel PATH
                                      [--source-path PATH]
                                      [--profilers "ncu proton"]
                                      [--profile-iters N] ...
                                      [--test-timeout-s N]

Examples:
  experiment-kernels.py run webinar-v1 --problems "matmul_bias flash_attention" \
      --case 3 --opt-rounds "5 10" --profilers ncu
  experiment-kernels.py run mixed-v1 --generation gpt-6.1-sol \
      --optimization claude-sonnet-4-6:high
  experiment-kernels.py profile webinar-v1 --profilers "nsys proton"
  experiment-kernels.py add-baseline webinar-v1 --problem matmul_bias \
      --label rocm_blog_fusion \
      --kernel problems/matmul_bias/baselines/rocm_blog_fusion.py
"""

