# Stage: profiler captures


def _profileable_variants(problem_rec: dict) -> list[dict]:
    """The variants a capture batch may profile: the verified generated
    baseline, every accepted *and verified* optimized kernel, and every
    verified external baseline. Failed, rejected, or unverified variants
    are never profiled — there is no verified source to attribute the
    capture to."""

    def entry(variant_key: str, impl: str, record: dict) -> dict:
        return {
            "variant": variant_key,
            "label": variant_key,
            "impl": impl,
            "kernel_path": record["kernel_path"],
            "kernel_sha256": record["kernel_sha256"],
        }

    variants = []
    generated = problem_rec.get("generated") or {}
    if generated.get("status") == "verified" and generated.get("kernel_path"):
        variants.append(entry(GENERATED_VARIANT, "kernel", generated))
    for variant_key, record in sorted(
        (problem_rec.get("variants") or {}).items()
    ):
        if (
            record.get("status") == "accepted"
            and record.get("verify_status") == "verified"
            and record.get("kernel_path")
        ):
            variants.append(entry(variant_key, "optimized", record))
    for label, record in sorted(
        (problem_rec.get("baselines") or {}).items()
    ):
        if record.get("status") == "verified" and record.get("kernel_path"):
            # profile-kernel.py resolves --kernel explicitly, so the impl
            # only selects its Triton hook: "kernel".
            variants.append(entry(label, "kernel", record))
    return variants


def _tool_versions(profilers: list[str]) -> dict[str, str]:
    """Each requested profiler CLI's version, probed once per batch and
    handed to the profile-kernel.py children via KA_TOOL_VERSION_<TOOL>,
    so each capture's metadata records it without spawning its own
    `--version` subprocess. Proton's version rides the runtime fragment
    instead."""
    versions = {}
    tools = [tool for tool in ("ncu", "nsys") if tool in profilers]
    if tools:
        # Independent process spawns; probe them together like
        # _collect_environment does.
        with ThreadPoolExecutor(max_workers=len(tools)) as pool:
            probed = list(
                pool.map(ka_common.probe_tool_version, tools)
            )
        for tool, version in zip(tools, probed):
            if version is not None:
                versions[f"KA_TOOL_VERSION_{tool.upper()}"] = version
    return versions


def _archived_kernel(
    exp_dir: Path, variant: dict
) -> tuple[Path | None, str | None, str | None]:
    """The archived kernel a capture must execute, plus the refusal
    status/reason when it is missing or no longer matches its recorded
    hash — a capture must never be attributed to a missing or replaced
    file."""
    kernel = exp_dir / variant["kernel_path"]
    if not kernel.is_file():
        return None, "missing_kernel", "archived kernel is missing"
    if sha256_file(kernel) != variant["kernel_sha256"]:
        return (
            None,
            "hash_mismatch",
            "archived kernel no longer matches its recorded hash",
        )
    return kernel, None, None


def _refusal_record(
    name: str, variant: dict, status: str, reason: str
) -> dict:
    """A capture-batch entry for a variant that was not profiled."""
    return {
        "problem": name,
        "variant": variant["variant"],
        "profiler": None,
        "status": status,
        "failure": {"stage": "capture", "reason": reason},
    }


def _capture_failure(
    record: dict, status: str, message: str, reason: str
) -> dict:
    """Mark a capture record failed with the one-line warning naming the
    capture; the artifacts stay on disk for diagnosis."""
    record["status"] = status
    record["failure"] = {"stage": "capture", "reason": reason}
    print(
        f"WARNING: {record['problem']}/{record['variant']}/"
        f"{record['profiler']} {message}"
    )
    return record


def _run_one_capture(
    exp_dir: Path,
    captures_dir: Path,
    case: int,
    name: str,
    variant: dict,
    kernel: Path,
    profiler: str,
    batch: dict,
    env: dict[str, str],
) -> tuple[str, dict]:
    """Spawn one profile-kernel.py capture and return its (manifest key,
    record). Failures — nonzero exit, unreadable metadata, or metadata
    describing different bytes — are recorded, never raised."""
    iters = batch["iters"]["default"]
    warmup = batch["warmup"]
    ncu_set = batch["ncu_set"]
    key = f"{name}/{variant['variant']}/{profiler}"
    stem = captures_dir / name / f"{variant['label']}_{profiler}_case{case}"
    ka_common.print_banner(
        f"[{name}/{variant['variant']}] {profiler} capture "
        f"(case {case}, {iters} iterations)"
    )
    result = subprocess.run(
        [
            sys.executable,
            str(_script_path(PROFILE_SCRIPT)),
            name,
            "--case",
            str(case),
            "--impl",
            variant["impl"],
            "--kernel",
            str(kernel),
            "--label",
            variant["label"],
            "--out",
            str(captures_dir),
            "--profiler",
            profiler,
            "--iters",
            str(iters),
            "--warmup",
            str(warmup),
            "--ncu-set",
            ncu_set,
        ],
        env=env,
    )
    record = {
        "problem": name,
        "variant": variant["variant"],
        "profiler": profiler,
        "label": variant["label"],
        "iters": iters,
        "status": "ok",
        "report_path": None,
        "metadata_path": None,
        "exports": [],
        "kernel_sha256": variant["kernel_sha256"],
        "failure": None,
    }
    meta_path = Path(f"{stem}.json")
    if result.returncode != 0 or not meta_path.is_file():
        return key, _capture_failure(
            record,
            "failed",
            "capture failed",
            f"profile-kernel.py exited {result.returncode}",
        )
    meta = load_json_object(meta_path)
    if meta is None:
        return key, _capture_failure(
            record,
            "failed",
            "capture failed",
            "capture metadata is unreadable",
        )
    if meta.get("kernel_sha256") != record["kernel_sha256"]:
        # The profiler snapshots and hashes the source it executes; a hash
        # that differs from the archived variant's — or is missing — means
        # the measurements cannot be attributed to this kernel. The
        # artifacts stay on disk for diagnosis, but a mismatched capture
        # is not a successful one.
        record["metadata_path"] = _rel(exp_dir, meta_path)
        return key, _capture_failure(
            record,
            "hash_mismatch",
            "capture attribution mismatch",
            "capture metadata does not describe the archived kernel",
        )
    record.update(
        {
            # The published report path, as recorded by profile-kernel.py
            # itself (the naming convention has one owner) and relativized
            # into the experiment here.
            "report_path": (
                _maybe_rel(exp_dir, meta["report"])
                if meta.get("report")
                else None
            ),
            "metadata_path": _rel(exp_dir, meta_path),
            "exports": [
                {
                    **export,
                    "paths": [
                        _maybe_rel(exp_dir, p)
                        for p in export.get("paths", [])
                    ],
                }
                for export in meta.get("exports", [])
            ],
            "gpu": meta.get("gpu"),
            "torch": meta.get("torch"),
            "triton": meta.get("triton"),
            "profiler_version": meta.get("profiler_version"),
        }
    )
    return key, record


def _run_capture_batch(
    exp_dir: Path,
    manifest: dict,
    profilers: list[str],
    profile_iters: int,
    profile_warmup: int,
    ncu_set: str,
    problems_filter: list[str] | None,
    variant_filter: set[tuple[str, str]] | None = None,
) -> bool:
    """Profile every profileable variant with every requested profiler,
    sequentially (profiler replays and captures must not overlap on the
    GPU), into one new capture batch directory. variant_filter, when
    given, restricts the batch to those (problem, variant) pairs — the
    add-baseline path captures only the kernel it just added."""
    case = manifest["configuration"]["case"]
    capture_id = (
        f"capture_{datetime.now():%Y%m%d_%H%M%S}_{secrets.token_hex(2)}"
    )
    captures_dir = exp_dir / "captures" / capture_id
    batch = {
        "capture_id": capture_id,
        "created_at": datetime.now().isoformat(),
        "profilers": profilers,
        "iters": {"default": profile_iters},
        "warmup": profile_warmup,
        "ncu_set": ncu_set,
        "captures": {},
        "status": None,
    }
    tool_versions = _tool_versions(profilers)
    capture_env = {**_stage_env(exp_dir, None), **tool_versions}

    attempted = 0
    failed = 0
    for name, problem_rec in manifest["problems"].items():
        if problems_filter and name not in problems_filter:
            continue
        variants = _profileable_variants(problem_rec)
        if not variants:
            print(f"[{name}] no verified variants to profile; skipping")
            continue
        if variant_filter is not None:
            variants = [
                v for v in variants if (name, v["variant"]) in variant_filter
            ]
        for variant in variants:
            kernel, status, reason = _archived_kernel(exp_dir, variant)
            if kernel is None:
                attempted += 1
                failed += 1
                batch["captures"][
                    f"{name}/{variant['variant']}"
                ] = _refusal_record(name, variant, status, reason)
                print(
                    f"WARNING: [{name}/{variant['variant']}] {reason}; "
                    "refusing to profile"
                )
                continue
            for profiler in profilers:
                attempted += 1
                key, record = _run_one_capture(
                    exp_dir,
                    captures_dir,
                    case,
                    name,
                    variant,
                    kernel,
                    profiler,
                    batch,
                    capture_env,
                )
                if record["status"] != "ok":
                    failed += 1
                batch["captures"][key] = record

    if attempted == 0:
        print("WARNING: no variants were profiled")
        batch["status"] = "empty"
        manifest.setdefault("capture_batches", []).append(batch)
        return True
    batch["status"] = (
        "completed"
        if failed == 0
        else "partial"
        if failed < attempted
        else "failed"
    )
    manifest.setdefault("capture_batches", []).append(batch)
    print(f"Capture batch {capture_id}: {batch['status']} "
          f"({attempted - failed}/{attempted} captures ok)")
    return failed == 0


